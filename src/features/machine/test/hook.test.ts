import { afterEach, beforeEach, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { git } from "../../../git.ts";
import { hookNote, hookState, installHook } from "../hook.ts";
import { loadOffice } from "../../../office.ts";

let dir: string;
let office: string;
const previous = { PATH: process.env.PATH, XDG_DATA_HOME: process.env.XDG_DATA_HOME };

beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), "office-hook-"));
  office = join(dir, "office");
  mkdirSync(join(dir, "bin"), { recursive: true });
  mkdirSync(office);
  writeFileSync(join(office, "office.yaml"), "name: t\n");
  // git, and a pre-commit of the test's own, but no mise: the hook comes from the pre-commit on PATH.
  process.env.PATH = `${join(dir, "bin")}:/usr/bin:/bin`;
  process.env.XDG_DATA_HOME = join(dir, "data");
});

afterEach(() => {
  for (const key of ["PATH", "XDG_DATA_HOME"] as const) {
    if (previous[key] === undefined) delete process.env[key];
    else process.env[key] = previous[key];
  }

  rmSync(dir, { recursive: true, force: true });
});

/** A pre-commit that reports its version and, for `install`, writes a hook as pre-commit does, counting installs. */
function fakePreCommit(): void {
  writeFileSync(join(dir, "bin/pre-commit"), `#!${process.execPath}
const fs = require("node:fs");
if (process.argv[2] === "--version") { console.log("pre-commit 4.7.0"); process.exit(0); }
fs.appendFileSync(${JSON.stringify(join(dir, "installs"))}, "install\\n");
fs.writeFileSync(".git/hooks/pre-commit", "#!/usr/bin/env bash\\n# File generated by pre-commit: https://pre-commit.com\\n", { mode: 0o755 });
`, { mode: 0o755 });
}

const installs = () => readFileSync(join(dir, "installs"), "utf8").split("\n").filter((line) => line !== "").length;

test("the hook is installed once, in an office that is a repository with a pre-commit config", () => {
  fakePreCommit();

  expect(hookState(loadOffice(office))).toEqual({ kind: "no-repository" });
  expect(installHook(loadOffice(office))).toBeUndefined();

  git(["init", "--quiet", office]);

  expect(hookState(loadOffice(office))).toEqual({ kind: "no-config" });

  writeFileSync(join(office, ".pre-commit-config.yaml"), "repos: []\n");

  expect(hookNote(hookState(loadOffice(office))).warn).toBe(true);
  expect(installHook(loadOffice(office))).toBe(`pre-commit hook: installed in ${join(office, ".git/hooks/pre-commit")} with pre-commit 4.7.0, so commits run the hooks in .pre-commit-config.yaml`);
  expect(installHook(loadOffice(office))).toBeUndefined();
  expect(installs()).toBe(1);
  expect(hookState(loadOffice(office)).kind).toBe("installed");
});

test("a hook of the user's own, or core.hooksPath, is left alone and reported", () => {
  fakePreCommit();
  git(["init", "--quiet", office]);
  writeFileSync(join(office, ".pre-commit-config.yaml"), "repos: []\n");
  writeFileSync(join(office, ".git/hooks/pre-commit"), "#!/bin/sh\necho mine\n", { mode: 0o755 });

  expect(installHook(loadOffice(office))).toStartWith(`pre-commit hook: ${join(office, ".git/hooks/pre-commit")} is a hook of your own`);
  expect(readFileSync(join(office, ".git/hooks/pre-commit"), "utf8")).toBe("#!/bin/sh\necho mine\n");

  git(["config", "core.hooksPath", ".githooks"], office);

  expect(installHook(loadOffice(office))).toStartWith("pre-commit hook: core.hooksPath is .githooks, where pre-commit won't install its hook");
  expect(() => readFileSync(join(dir, "installs"))).toThrow();
});

test("without pre-commit, the hook waits for office setup", () => {
  git(["init", "--quiet", office]);
  writeFileSync(join(office, ".pre-commit-config.yaml"), "repos: []\n");

  expect(installHook(loadOffice(office))).toBe("pre-commit hook: not installed, as pre-commit isn't installed yet; office setup installs both");
});
