// A package's `down` in the compiled office: the shutdown reader runs every `down` it can, leaves
// out each package that fails a check or doesn't import and the packages that depend on it, runs no
// `setup`, and never keeps the office's own shutdown from completing. Docker and systemd are fakes
// that record their calls; the kernel's shutdown shows in them as Compose's `down` and the removal of
// the image refresh timer.
import { expect, test } from "bun:test";
import { existsSync, mkdirSync, renameSync, rmSync, symlinkSync } from "node:fs";
import { join } from "node:path";
import { git } from "./git.ts";
import { definitionFixture, type DefinitionFixture } from "./package-definition.fixture.ts";
import { definitionText, writePackage } from "./test-package.ts";

const { root, marker, write, read, commit, fixture } = definitionFixture({ second: false });

const fs = 'import {existsSync, rmSync} from "node:fs"; import {join} from "node:path";';

/** Fakes recording each call in $HOME/calls, and an installed image refresh timer for the kernel's shutdown to remove. */
function rig(f: DefinitionFixture) {
  const name = f.dir.split("/").at(-1);

  write(join(f.home, "bin/docker"), '#!/bin/sh\necho "docker $*" >> "$HOME/calls"\nexit 0\n', 0o755);
  write(join(f.home, "bin/systemctl"), '#!/bin/sh\necho "systemctl $*" >> "$HOME/calls"\nexit 0\n', 0o755);

  const arm = () => { for (const suffix of ["timer", "service"]) write(join(f.home, `units/office-${name}-refresh-image.${suffix}`), `# Generated by \`office up\` for the ${name} office. Don't edit\n`); };

  arm();

  // Checks the last shutdown's calls, then installs the timer again for the next.
  return () => {
    const calls = read(join(f.home, "calls"));

    // The office's own shutdown completed: the refresh timer is stopped and gone, and Compose took the project down.
    expect(calls).toContain(`systemctl --user disable --now office-${name}-refresh-image.timer`);
    expect(calls).toMatch(new RegExp(`docker compose -p office-${name} .* down\\n`));
    expect(existsSync(join(f.home, `units/office-${name}-refresh-image.timer`))).toBe(false);
    rmSync(join(f.home, "calls"));
    arm();
  };
}

/** A package whose `down` removes `<office>/<name>-marker` and says whether it was given `entries`. */
const removing = (name: string, extra = "") => definitionText(`{${extra}
  down(inputs) { rmSync(join(inputs.office.dir, "${name}-marker")); return ["removed its marker", "entries: " + typeof inputs.entries] }}`, fs);

const markers = (f: DefinitionFixture, ...names: string[]) => { for (const name of names) write(join(f.dir, `${name}-marker`), ""); };

const exists = (f: DefinitionFixture, name: string) => existsSync(join(f.dir, `${name}-marker`));

test("a definition that can't be imported, settings that aren't valid and a down that throws are each named and left out; every other down runs, with no setup and no entries; the office's own shutdown completes", () => {
  const f = fixture("down");
  const shutdown = rig(f);
  const typed = 'settings: {type: "object", additionalProperties: false, properties: {count: {type: "integer", default: 1}}}, setup() { throw Error("setup boom") },';
  writePackage(join(f.dir, "packages/keeper/office.ts"), removing("keeper", typed));
  writePackage(join(f.dir, "packages/broken/office.ts"), removing("broken"));
  writePackage(join(f.dir, "packages/thrower/office.ts"), definitionText('{down() { throw Error("down boom") }}'));
  writePackage(join(f.dir, "packages/later/office.ts"), removing("later"));
  f.select("  - name: keeper\n  - name: broken\n  - name: thrower\n  - name: later\n");
  // Keeper's setup throws, so sync rejects the set; with it fixed for the sync, the published set has all four.
  writePackage(join(f.dir, "packages/keeper/office.ts"), removing("keeper"));
  f.cli(0, "sync", "--packages");
  writePackage(join(f.dir, "packages/keeper/office.ts"), removing("keeper", typed));

  // A setup that would throw isn't seen: down runs no setup, and passes no entries.
  markers(f, "keeper", "broken", "later");
  writePackage(join(f.dir, "packages/thrower/office.ts"), definitionText("{}"));
  const clean = f.cli(0, "down");
  expect(clean).toContain("package keeper: removed its marker\npackage keeper: entries: undefined\n");
  expect(["keeper", "broken", "later"].some(name => exists(f, name))).toBe(false);
  shutdown();

  markers(f, "keeper", "broken", "later");
  writePackage(join(f.dir, "packages/thrower/office.ts"), definitionText('{down() { throw Error("down boom") }}'));
  writePackage(join(f.dir, "packages/broken/office.ts"), `${marker} throw Error("broken on import");`);
  write(join(f.dir, "office.yaml"), read(join(f.dir, "office.yaml")).replace("  - name: keeper\n", "  - name: keeper\n    settings: {count: many}\n"));
  const output = f.cli(1, "down");
  expect(output).toContain("package broken: left out of shutdown, so what it installed, such as its timers, stays installed: packages/broken/office.ts: broken on import");
  expect(output).toContain("package keeper: its down didn't run: packages.keeper.settings.count: must be integer");
  expect(output).toContain("package thrower: its down failed: down boom");
  expect(output).toContain("package later: removed its marker");
  expect(output).toContain("office: the office's own shutdown completed, but not every package's (above)");
  expect(exists(f, "keeper")).toBe(true);
  expect(exists(f, "later")).toBe(false);
  shutdown();
}, 60_000);

test("a tampered provider, or one whose definition doesn't import, is left out with the dependent before it, which is never imported; a third package's down runs", () => {
  const f = fixture("tampered");
  const shutdown = rig(f);
  const repo = join(root, "tampered-source");
  git(["init", "-qb", "main", repo]);
  write(join(repo, "provider/items.ts"), 'export const items = {id: "provider.items", parse: (entry: unknown) => entry};');
  writePackage(join(repo, "provider/office.ts"), definitionText("{}"), { name: "provider", exports: { "./items": "./items.ts" } });
  const pinned = commit(repo);
  writePackage(join(f.dir, "packages/consumer/office.ts"), removing("consumer"), { dependencies: ["provider"] });
  write(join(f.dir, "packages/consumer/office.ts"), `import {items} from "@office/provider/items"; void items;\n${read(join(f.dir, "packages/consumer/office.ts"))}`);
  writePackage(join(f.dir, "packages/third/office.ts"), removing("third"));
  // A local provider and a dependent that would write the probe if it were imported.
  write(join(f.dir, "packages/lender/items.ts"), 'export const items = {id: "lender.items"};');
  writePackage(join(f.dir, "packages/lender/office.ts"), definitionText("{}"), { exports: { "./items": "./items.ts" } });
  writePackage(join(f.dir, "packages/borrower/office.ts"), removing("borrower"), { dependencies: ["lender"] });
  write(join(f.dir, "packages/borrower/office.ts"), `import {items} from "@office/lender/items"; void items; ${marker}\n${read(join(f.dir, "packages/borrower/office.ts"))}`);
  // Each consumer comes before its provider.
  f.select(`  - name: consumer\n  - {name: provider, repo: ${repo}, path: provider, ref: ${pinned}}\n  - name: borrower\n  - name: lender\n  - name: third\n`);
  f.cli(0, "sync", "--packages");
  rmSync(f.probe, { force: true });

  const items = join(f.dir, ".office/packages/provider/items.ts");
  write(items, `${marker}\n${read(items)}`);
  write(join(f.dir, "packages/lender/office.ts"), 'throw Error("lender on import");');
  markers(f, "consumer", "borrower", "third");
  const output = f.cli(1, "down");
  expect(output).toContain("package provider: left out of shutdown, so what it installed, such as its timers, stays installed: package files edited: items.ts (edited)");
  expect(output).toContain("package consumer: left out of shutdown, so what it installed, such as its timers, stays installed: depends on package provider, which is left out");
  expect(output).toContain("package lender: left out of shutdown, so what it installed, such as its timers, stays installed: packages/lender/office.ts: lender on import");
  expect(output).toContain("package borrower: left out of shutdown, so what it installed, such as its timers, stays installed: depends on package lender, which is left out");
  expect(output).toContain("package third: removed its marker");
  expect(existsSync(f.probe)).toBe(false);
  expect(exists(f, "consumer")).toBe(true);
  expect(exists(f, "borrower")).toBe(true);
  expect(exists(f, "third")).toBe(false);
  shutdown();

  // A command with the same set imports nothing either, and fails naming the provider.
  expect(f.cli(1, "references", "list")).toContain("package provider: package files edited: items.ts (edited)");
  expect(existsSync(f.probe)).toBe(false);
}, 60_000);

/** A consumer of the optional `provider`, whose integration module writes the probe when imported and adds nothing. */
function consumer(f: DefinitionFixture, provider: string) {
  const dir = join(f.dir, "packages/consumer");

  writePackage(join(dir, "office.ts"), removing("consumer", `settings: {type: "object", additionalProperties: false, properties: {lend: {type: "boolean"}}},`));
  write(join(dir, "adapter.ts"), `import { Package } from "@office/sdk"; ${marker}\nexport default Package.integration()({ setup() {} });\n`);
  write(join(dir, "package.json"), JSON.stringify({ name: "@office/consumer", office: { definition: "./office.ts", integrations: { [`@office/${provider}`]: "./adapter.ts" } } }));
}

const leftOut = (name: string, why: string) => `package ${name}: left out of shutdown, so what it installed, such as its timers, stays installed: ${why}`;

test("a selected optional provider is an edge in shutdown whatever its consumer's settings, and no integration is evaluated; a deselected one is none", () => {
  const f = fixture("optional");
  const shutdown = rig(f);
  consumer(f, "lender");
  writePackage(join(f.dir, "packages/lender/office.ts"), definitionText("{}"));
  writePackage(join(f.dir, "packages/third/office.ts"), removing("third"));
  f.select("  - name: consumer\n    settings: {lend: true}\n  - name: lender\n  - name: third\n");
  f.cli(0, "sync", "--packages");
  // Sync ran the integration; down must not.
  expect(read(f.probe)).toBe("imported\n");
  rmSync(f.probe);

  // Healthy: every down runs, the integration unevaluated.
  markers(f, "consumer", "third");
  const healthy = f.cli(0, "down");
  expect(healthy).toContain("package consumer: removed its marker");
  expect(healthy).toContain("package third: removed its marker");
  expect(existsSync(f.probe)).toBe(false);
  shutdown();

  // Settings that lend nothing, with the provider failing to import: the consumer is still left out with it.
  f.select("  - name: consumer\n    settings: {lend: false}\n  - name: lender\n  - name: third\n");
  write(join(f.dir, "packages/lender/office.ts"), 'throw Error("lender on import");');
  markers(f, "consumer", "third");
  const output = f.cli(1, "down");
  expect(output).toContain(leftOut("lender", "packages/lender/office.ts: lender on import"));
  expect(output).toContain(leftOut("consumer", "depends on package lender, which is left out"));
  expect(output).toContain("package third: removed its marker");
  expect(exists(f, "consumer")).toBe(true);
  expect(existsSync(f.probe)).toBe(false);
  shutdown();

  // Deselected, the provider is no edge: the consumer's down runs, its integration unevaluated.
  f.select("  - name: consumer\n  - name: third\n");
  f.cli(0, "sync", "--packages");
  markers(f, "consumer", "third");
  expect(f.cli(0, "down")).toContain("package consumer: removed its marker");
  expect(exists(f, "consumer")).toBe(false);
  expect(existsSync(f.probe)).toBe(false);
  shutdown();
}, 60_000);

test("a selected optional provider left out of resolution for an ownership conflict still takes its consumer with it; independent packages and the office's own shutdown run", () => {
  const f = fixture("conflict");
  const shutdown = rig(f);
  consumer(f, "skills");
  writePackage(join(f.dir, "packages/third/office.ts"), removing("third"));
  f.select("  - name: consumer\n  - name: skills\n  - name: third\n");
  f.cli(0, "sync", "--packages");
  // Sync ran the integration; down must not.
  expect(read(f.probe)).toBe("imported\n");
  rmSync(f.probe);

  // A local folder now claims the built-in's name.
  mkdirSync(join(f.dir, "packages/skills"));
  markers(f, "consumer", "third");
  const output = f.cli(1, "down");
  expect(output).toContain(leftOut("skills", "built-in package skills conflicts with local packages/skills; rename one before syncing"));
  expect(output).toContain(leftOut("consumer", "depends on package skills, which is left out"));
  expect(output).toContain("package third: removed its marker");
  expect(exists(f, "consumer")).toBe(true);
  expect(existsSync(f.probe)).toBe(false);
  shutdown();
}, 60_000);

test("with no published package set no package takes part, and a shutdown reader that can't start, or a redirected generations folder, doesn't keep the office's own shutdown from completing", () => {
  const f = fixture("unread");
  const shutdown = rig(f);
  writePackage(join(f.dir, "packages/keeper/office.ts"), removing("keeper"));
  f.select("  - name: keeper\n");
  f.cli(0, "sync", "--packages");
  const pointer = join(f.dir, ".office/current");

  // A pointer that names no generation: the reader can't be started.
  markers(f, "keeper");
  rmSync(pointer);
  symlinkSync("generations/../elsewhere", pointer);
  const unstarted = f.cli(1, "down");
  expect(unstarted).toContain("office: the packages' shutdown couldn't start: invalid managed package pointer");
  expect(unstarted).toContain("office: the office's own shutdown completed, but not every package's (above)");
  expect(exists(f, "keeper")).toBe(true);
  shutdown();

  // A redirected generations folder: the pointer still resolves through it, but nothing is pinned or
  // imported there, and the office's own shutdown still completes.
  rmSync(pointer);
  f.cli(0, "sync", "--packages");
  const generations = join(f.dir, ".office/generations");
  renameSync(generations, join(f.home, "redirected"));
  symlinkSync(join(f.home, "redirected"), generations);
  write(join(f.dir, "packages/keeper/office.ts"), `${marker}\n${read(join(f.dir, "packages/keeper/office.ts"))}`);
  const redirected = f.cli(1, "down");
  expect(redirected).toContain(`office: the packages' shutdown couldn't start: cannot use redirected or non-directory ${generations}`);
  expect(redirected).toContain("office: the office's own shutdown completed, but not every package's (above)");
  expect(existsSync(f.probe)).toBe(false);
  expect(exists(f, "keeper")).toBe(true);
  shutdown();
  rmSync(generations);
  renameSync(join(f.home, "redirected"), generations);

  // No pointer at all: as in an office that never synced.
  rmSync(pointer);
  expect(f.cli(0, "down")).toContain("office: no package set is published, so no package took part in the shutdown");
  expect(exists(f, "keeper")).toBe(true);
  shutdown();
}, 60_000);
