// git's pre-commit hook in an office's clone, which runs the hooks in its .pre-commit-config.yaml
// (the template's gitleaks hook blocks commits that contain secrets). A clone gets no hook from the
// repository, so `office init` and `office setup` install it with the office package's pre-commit
// (`pre-commit install`), once: a hook pre-commit wrote is left as it is, and one the user wrote is
// never replaced. With core.hooksPath set, pre-commit refuses to install, so office only says so.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, realpathSync } from "node:fs";
import { isAbsolute, join } from "node:path";

import { git } from "./git.ts";
import { officeTool } from "./host-tools.ts";
import type { Office } from "./office.ts";

const config = ".pre-commit-config.yaml";

/** The line pre-commit writes at the top of every hook it installs. */
const generated = "# File generated by pre-commit";

/** The hook's state in the office's clone. */
export type HookState =
  | { kind: "no-repository" }
  | { kind: "no-config" }
  | { kind: "hooks-path"; path: string }
  | { kind: "installed"; path: string }
  | { kind: "own"; path: string }
  | { kind: "missing"; path: string };

/** Whether the office's folder is the top of a git work tree of its own. */
function isRepository(office: Office): boolean {
  try {
    return realpathSync(git(["rev-parse", "--show-toplevel"], office.dir)) === realpathSync(office.dir);
  } catch {
    return false;
  }
}

function setting(office: Office, key: string): string | undefined {
  try {
    return git(["config", "--get", key], office.dir) || undefined;
  } catch {
    return undefined;
  }
}

export function hookState(office: Office): HookState {
  if (!isRepository(office)) return { kind: "no-repository" };

  if (!existsSync(join(office.dir, config))) return { kind: "no-config" };

  const hooksPath = setting(office, "core.hooksPath");

  if (hooksPath !== undefined) return { kind: "hooks-path", path: hooksPath };

  const relative = git(["rev-parse", "--git-path", "hooks/pre-commit"], office.dir);
  const path = isAbsolute(relative) ? relative : join(office.dir, relative);

  if (!existsSync(path)) return { kind: "missing", path };

  return readFileSync(path, "utf8").split("\n").slice(0, 3).some((line) => line.startsWith(generated)) ? { kind: "installed", path } : { kind: "own", path };
}

/** What `office check` says of the hook, and whether it is a warning. */
export type HookNote = { warn: boolean; detail: string };

export function hookNote(state: HookState): HookNote {
  switch (state.kind) {
    case "no-repository":
      return { warn: false, detail: "the office isn't a git repository of its own, so there is no hook to run" };
    case "no-config":
      return { warn: false, detail: `no ${config}, so there are no hooks to run` };
    case "hooks-path":
      return { warn: true, detail: `core.hooksPath is ${state.path}, where pre-commit won't install its hook, so the hooks in ${config} don't run on commit unless a hook there runs pre-commit` };
    case "installed":
      return { warn: false, detail: `installed in ${state.path}, so commits run the hooks in ${config}` };
    case "own":
      return { warn: true, detail: `${state.path} is a hook of your own, so the hooks in ${config} don't run unless it runs them; pre-commit install would keep it as pre-commit.legacy and run both` };
    case "missing":
      return { warn: true, detail: `not installed, so commits don't run the hooks in ${config}; office setup installs it (pre-commit install)` };
  }
}

/** Installs the hook when it is missing, with the office package's pre-commit. Returns what happened, for messages. */
export function installHook(office: Office): string | undefined {
  const state = hookState(office);

  if (state.kind !== "missing") return state.kind === "hooks-path" || state.kind === "own" ? `pre-commit hook: ${hookNote(state).detail}` : undefined;

  const preCommit = officeTool(office, "pre-commit");

  if (preCommit === undefined) return `pre-commit hook: not installed, as pre-commit isn't installed yet; office setup installs both`;

  try {
    execFileSync(preCommit.path, ["install"], { cwd: office.dir, stdio: ["ignore", "pipe", "pipe"], timeout: 120_000 });
  } catch {
    return `pre-commit hook: pre-commit install failed in ${office.dir}; run it there yourself`;
  }

  return `pre-commit hook: installed in ${state.path} with pre-commit ${preCommit.version}, so commits run the hooks in ${config}`;
}
