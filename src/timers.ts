// The office's systemd user timers, each a timer and a oneshot service, both with Persistent=true so
// systemd runs one missed while the computer was off. The one implementation of writing them: the
// kernel's own (the weekly image refresh) and each package's, through `host.timers`, all go through
// here. A unit is named office-<office>-<package>-<id>, or office-<office>-<reserved> for the
// kernel's own, and starts with a header naming the exact office. Who owns a unit is read from the
// file, never guessed from a prefix: the first part of the name after the office's prefix for a
// package whose name has no dash (the header cron's timers had before cron was a package, so they
// are adopted in place), an owner line under the header for one whose name has a dash, so `a` and
// `a-b` can't reach each other's units. A file at
// a wanted name that another owner or nobody wrote is refused, as is a unit systemd loaded from
// another file. With a git identity in office.yaml, each service's GIT_CONFIG_GLOBAL is a generated
// file that includes the user's global git config and then sets that identity, so an unattended
// run commits as the office without the host's global identity changing.
import { execFileSync } from "node:child_process";
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

import * as v from "valibot";

import type { Timer, TimerState } from "../sdk/index.ts";
import { type Office, OfficeError } from "./office.ts";
import { argument, quoted, requireLocalUnit, systemctl, unitDir, unitDirVariable } from "./systemd.ts";
import { officeCommand } from "./tool.ts";

/** A timer to write: its unit name without the suffix, OnCalendar value, a description, and the `office` arguments its service runs. */
export type UnitTimer = { unit: string; calendar: string; description: string; args: readonly string[] };

/** The kernel's own units, by what follows `office-<office>-`; no package timer may have one of these names. */
const reserved = ["refresh-image"] as const;

/** Who a unit belongs to: a package by name, or one of the kernel's reserved units. */
export type TimerOwner = { package: string } | { reserved: (typeof reserved)[number] };

/** A generated unit's owner as read from it, or `unknown`: a name no package can own, or an owner line that doesn't fit it. */
type FoundOwner = TimerOwner | { unknown: true };

// Marks a unit as generated, so office only touches its own files.
const marker = "# Generated by `office up`";

const prefix = (office: Pick<Office, "name">) => `office-${office.name}-`;

const header = (office: Pick<Office, "name">) => `${marker} for the ${office.name} office. Don't edit: \`office up\` rewrites it and \`office down\` removes it.`;

const ownerLine = (name: string) => `# Owner: package ${name}`;

const packageName = /^[a-z0-9][a-z0-9-]*$/;

const timerId = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;

// What systemd's calendar syntax uses, on one line: no specifier, quote or escape.
const calendarText = /^[A-Za-z0-9*,:./~+_-]+(?: [A-Za-z0-9*,:./~+_-]+)*$/;

function ownerOf(rest: string, second: string | undefined): FoundOwner {
  const kernel = reserved.find(name => name === rest);

  if (kernel) return { reserved: kernel };
  const explicit = second === undefined ? undefined : /^# Owner: package (.*)$/.exec(second)?.[1];

  if (explicit !== undefined) return packageName.test(explicit) && rest.startsWith(`${explicit}-`) && rest.length > explicit.length + 1 ? { package: explicit } : { unknown: true };
  const dash = rest.indexOf("-");

  return dash <= 0 || dash === rest.length - 1 ? { unknown: true } : { package: rest.slice(0, dash) };
}

function owns(found: FoundOwner, owner: TimerOwner): boolean {
  if ("package" in owner) return "package" in found && found.package === owner.package;

  return "reserved" in found && found.reserved === owner.reserved;
}

const label = (owner: TimerOwner) => "package" in owner ? owner.package : owner.reserved;

/** Every unit file `office up` generated for this office whose name starts with `start`, with its owner. */
function markedUnits(office: Pick<Office, "name">, start = prefix(office)): { file: string; owner: FoundOwner }[] {
  const dir = unitDir();

  if (!existsSync(dir)) return [];

  return readdirSync(dir, { withFileTypes: true }).flatMap((file) => {
    const suffix = /\.(service|timer)$/.exec(file.name);

    if (!file.isFile() || !file.name.startsWith(start) || !suffix) return [];
    const text = readFileSync(join(dir, file.name), "utf8");

    if (!text.startsWith(`${marker} for the ${office.name} office. `)) return [];

    return [{ file: file.name, owner: ownerOf(file.name.slice(prefix(office).length, suffix.index), text.split("\n")[1]) }];
  });
}

/** What every unit name of `owner` starts with. */
const ownerStart = (office: Pick<Office, "name">, owner: TimerOwner) => `${prefix(office)}${"package" in owner ? `${owner.package}-` : `${owner.reserved}.`}`;

/** The unit files of `owner`; no file outside its names is read. */
export function ownedUnits(office: Pick<Office, "name">, owner: TimerOwner): string[] {
  return markedUnits(office, ownerStart(office, owner)).filter(unit => owns(unit.owner, owner)).map(unit => unit.file);
}

/** Every generated unit of the office but the kernel's reserved ones: what container mode removes before it starts. */
export function packageUnits(office: Pick<Office, "name">): string[] {
  return markedUnits(office).filter(unit => !("reserved" in unit.owner)).map(unit => unit.file);
}

/**
 * The PATH `office up` ran with, so a service finds mise and the tools it calls (and Bun, for a
 * checkout's launcher), without mise's per-version install folders: an upgrade removes those, and
 * mise's shims resolve each tool for the folder the service runs in.
 */
function servicePath(): string {
  const dirs: string[] = [];

  for (const dir of (process.env.PATH ?? "/usr/bin:/bin").split(":")) {
    const installs = dir.indexOf("/mise/installs/");
    // `mise activate` puts install folders on PATH rather than the shims, so each becomes the
    // shims folder of the same mise, which then provides those tools, such as sops for `office up`.
    const entry = installs === -1 ? dir : `${dir.slice(0, installs)}/mise/shims`;

    if (!dirs.includes(entry)) dirs.push(entry);
  }

  return dirs.join(":");
}

/**
 * The environment `office up` ran with that the office's commands read: PATH, and the ports, so a
 * timer brings up an office started on other ports (EXECUTOR_PORT=42440) on the same ones.
 */
function serviceEnvironment(): string[] {
  const context = new Set([
    "HOME", "XDG_CONFIG_HOME", "XDG_DATA_HOME", "XDG_STATE_HOME", "XDG_CACHE_HOME", "TMPDIR",
    "MISE_CONFIG_DIR", "MISE_DATA_DIR", "MISE_STATE_DIR", "MISE_CACHE_DIR",
    unitDirVariable, "OFFICE_MACHINE_DIR", "OFFICE_MACHINE_RECORD", "OFFICE_MISE_CONFIG_DIR",
    "OFFICE_APP_CONFIG_DIR", "OFFICE_APP_PANELS_DIR",
  ]);

  const environment = [`PATH=${servicePath()}`];

  for (const [key, value] of Object.entries(process.env)) {
    if (value !== undefined && (key.endsWith("_PORT") || context.has(key))) environment.push(`${key}=${value}`);
  }

  return environment;
}

/**
 * The global git config the office's timers run with: the user's own (both places git reads it
 * from, or GIT_CONFIG_GLOBAL's file), then the office's identity. Undefined without an identity.
 */
function serviceGitConfig(office: Office): string | undefined {
  if (office.git?.name === undefined || office.git.email === undefined) return undefined;

  const path = join(office.state, "cron-gitconfig");
  const own = process.env.GIT_CONFIG_GLOBAL === undefined ? [join(process.env.XDG_CONFIG_HOME ?? join(homedir(), ".config"), "git/config"), join(homedir(), ".gitconfig")] : [process.env.GIT_CONFIG_GLOBAL];
  const set = (...args: string[]) => execFileSync("git", ["config", "--file", path, ...args], { stdio: "ignore" });

  mkdirSync(office.state, { recursive: true });
  rmSync(path, { force: true });

  // Git skips an included file that doesn't exist.
  for (const file of own) set("--add", "include.path", file);

  set("user.name", office.git.name);
  set("user.email", office.git.email);

  return path;
}

/** The unit name of a package's timer, refused when the name can't be one safe unit of that package. */
function packageTimerUnit(office: Pick<Office, "name">, name: string, id: string): string {
  if (!packageName.test(name)) throw new OfficeError(`${JSON.stringify(name)} is not a package name`);

  if (!timerId.test(id)) throw new OfficeError(`package ${name}: timer id ${JSON.stringify(id)} must be letters, digits, dots, dashes and underscores, starting with a letter or digit`);
  const rest = `${name}-${id}`;

  if (reserved.some(name => name === rest)) throw new OfficeError(`package ${name}: timer id ${id}: office-${office.name}-${rest} is office's own unit`);
  const unit = `${prefix(office)}${rest}`;

  if (`${unit}.service`.length > 255) throw new OfficeError(`package ${name}: timer ${id}: systemd unit name is too long; shorten the office or package name`);

  return unit;
}

function requireTimers(office: Pick<Office, "name">, owner: TimerOwner, wanted: readonly UnitTimer[]): void {
  const units = new Set<string>();

  for (const timer of wanted) {
    const rest = timer.unit.slice(prefix(office).length);
    const fits = timer.unit.startsWith(prefix(office)) && ("package" in owner ? rest.startsWith(`${owner.package}-`) && !reserved.some(name => name === rest) : rest === owner.reserved);

    if (!fits) throw new OfficeError(`${timer.unit} is not a unit name of ${label(owner)}`);

    if (units.has(timer.unit)) throw new OfficeError(`${timer.unit} is wanted twice`);
    units.add(timer.unit);

    if (!calendarText.test(timer.calendar)) throw new OfficeError(`${timer.unit}: ${JSON.stringify(timer.calendar)} is not a calendar a timer unit can hold`);

    if (timer.description.includes("\n") || timer.args.some(word => word.includes("\0"))) throw new OfficeError(`${timer.unit}: its description or words can't be written to a unit`);
  }
}

/** Stops and removes generated unit files; returns the line saying so, or none. */
function stopUnits(files: string[]): string[] {
  const timers = files.filter((file) => file.endsWith(".timer"));
  const services = files.filter((file) => file.endsWith(".service"));

  for (const file of files) requireLocalUnit(file);

  if (timers.length > 0) systemctl(["disable", "--now", ...timers]);

  if (services.length > 0) systemctl(["stop", ...services]);

  for (const file of files) rmSync(join(unitDir(), file));

  return files.length > 0 ? [`removed ${files.join(", ")}`] : [];
}

/** Stops and removes `files`, then reloads systemd; returns the lines to print. Nothing to remove needs no systemd. */
function removeUnits(files: string[]): string[] {
  if (files.length === 0) return [];
  const lines = stopUnits(files);

  systemctl(["daemon-reload"]);

  return lines;
}

/**
 * Makes `owner`'s timers equal `wanted`: removes its generated units not among them, writes the
 * wanted ones and starts them. Returns the lines to print.
 */
export function writeTimers(office: Office, owner: TimerOwner, wanted: readonly UnitTimer[]): string[] {
  requireTimers(office, owner, wanted);
  const dir = unitDir();
  const own = ownedUnits(office, owner);
  const keep = wanted.flatMap(({ unit }) => [`${unit}.timer`, `${unit}.service`]);

  for (const name of keep) {
    if (!own.includes(name) && lstatSync(join(dir, name), { throwIfNoEntry: false }) !== undefined) {
      throw new OfficeError(`${join(dir, name)} is not an office-generated ${label(owner)} unit; office leaves it alone`);
    }

    requireLocalUnit(name);
  }

  if (wanted.length === 0) return removeUnits(own);
  const lines = stopUnits(own.filter((file) => !keep.includes(file)));
  const gitConfig = serviceGitConfig(office);
  const environment = serviceEnvironment();
  // A package whose name has a dash says so under the header: its name's first part is another package's.
  const head = "package" in owner && owner.package.includes("-") ? [header(office), ownerLine(owner.package)] : [header(office)];

  mkdirSync(dir, { recursive: true });

  for (const timer of wanted) {
    const description = `Description=office ${office.name}: ${timer.description}`;

    writeFileSync(
      join(dir, `${timer.unit}.service`),
      [
        ...head,
        "[Unit]",
        description,
        "",
        "[Service]",
        "Type=oneshot",
        // Pass the office as an argument instead: WorkingDirectory= does not use ExecStart quoting.
        ...environment.map((variable) => `Environment=${quoted(variable)}`),
        ...(gitConfig === undefined ? [] : [`Environment=${quoted(`GIT_CONFIG_GLOBAL=${gitConfig}`)}`]),
        `ExecStart=${[officeCommand(), "--office", office.dir, ...timer.args].map(argument).join(" ")}`,
        "",
      ].join("\n"),
    );

    writeFileSync(
      join(dir, `${timer.unit}.timer`),
      [...head, "[Unit]", description, "", "[Timer]", `OnCalendar=${timer.calendar}`, "Persistent=true", "", "[Install]", "WantedBy=timers.target", ""].join("\n"),
    );
  }

  systemctl(["daemon-reload"]);
  systemctl(["enable", "--now", ...wanted.map((timer) => `${timer.unit}.timer`)]);

  return [...lines, ...wanted.map(timer => `timer ${timer.unit}: ${timer.calendar}, ${timer.description}`)];
}

/** Stops and removes every generated unit of `owner`; returns the lines to print. */
export function removeTimers(office: Pick<Office, "name">, owner: TimerOwner): string[] {
  return removeUnits(ownedUnits(office, owner));
}

/**
 * Before container mode starts its own scheduler: stops and removes every generated unit of the
 * office but the kernel's own, whoever's it is. One that can't be stopped stops `office up`.
 */
export function removePackageTimers(office: Pick<Office, "name">): string[] {
  const files = packageUnits(office);

  try {
    return removeUnits(files);
  } catch (error) {
    throw new OfficeError(`couldn't stop the host timers ${files.join(", ")}, so the container's scheduler doesn't start beside them: ${error instanceof Error ? error.message : String(error)}`);
  }
}

/**
 * The installed timers of `owner`, wanted or not, a service left without its timer too: each with
 * which files are there, what the timer file says and what systemd reports; a package's by its id.
 * A unit systemd loaded from another file is refused, as writing and removing refuse it.
 */
export function timerStatus(office: Pick<Office, "name">, owner: TimerOwner): TimerState[] {
  const start = "package" in owner ? ownerStart(office, owner) : prefix(office);
  const files = ownedUnits(office, owner);

  for (const file of files) requireLocalUnit(file);
  const names = [...new Set(files.map(file => file.slice(0, file.lastIndexOf("."))))].sort();

  return names.map((name): TimerState => {
    const id = name.slice(start.length);
    const timer = files.includes(`${name}.timer`);
    const service = files.includes(`${name}.service`);

    if (!timer) return { id, files: "service", active: false, calendar: "", persistent: false };
    const text = readFileSync(join(unitDir(), `${name}.timer`), "utf8");
    const shown = systemctl(["show", `${name}.timer`, "--property=ActiveState,NextElapseUSecRealtime,LastTriggerUSec"], { capture: true });
    const property = (key: string) => new RegExp(`^${key}=(.*)$`, "m").exec(shown)?.[1] || undefined;

    const state: TimerState = {
      id,
      files: service ? "pair" : "timer",
      active: property("ActiveState") === "active",
      calendar: /^OnCalendar=(.*)$/m.exec(text)?.[1] ?? "",
      persistent: /^Persistent=true$/m.test(text),
    };

    const next = property("NextElapseUSecRealtime");
    const last = property("LastTriggerUSec");

    if (next !== undefined) state.next = next;

    if (last !== undefined) state.last = last;

    return state;
  });
}

/** Container mode's weekly refresh of the opencode image, Sundays after the daily jobs. */
export function refreshTimer(office: Pick<Office, "name">): UnitTimer {
  return { unit: `${prefix(office)}refresh-image`, calendar: "Sun *-*-* 07:00:00 UTC", description: "office up --refresh", args: ["up", "--refresh"] };
}

export const refreshOwner: TimerOwner = { reserved: "refresh-image" };

/** A package's timer as `host.timers.set` takes it. */
const packageTimers = v.array(v.strictObject({ id: v.string(), calendar: v.string(), run: v.pipe(v.array(v.string()), v.minLength(1)) }));

/** `host.timers` for the package `name`: its own timers only. Setting them needs host mode. */
export function hostTimers(office: Office, name: string) {
  const owner = { package: name };

  return {
    set(timers: readonly Timer[]): readonly string[] {
      if (office.opencode.mode === "container") throw new OfficeError(`package ${name}: host timers can't be set in container mode`);
      // A package's code is plain JavaScript at run time, whatever its types said.
      const parsed = v.safeParse(packageTimers, timers);

      if (!parsed.success) throw new OfficeError(`package ${name}: host.timers.set takes a list of { id, calendar, run }`);

      return writeTimers(office, owner, parsed.output.map(timer => ({ unit: packageTimerUnit(office, name, timer.id), calendar: timer.calendar, description: timer.id, args: timer.run })));
    },
    clear: (): readonly string[] => removeTimers(office, owner),
    status: (): readonly TimerState[] => timerStatus(office, owner),
  };
}
