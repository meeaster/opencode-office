// The bytes `office up` writes for a cron job's timer and for the image refresh timer, and the
// systemctl calls that write them, fixed against the release before cron became a package (whose
// kernel wrote them): installed timers are adopted in place only while these stay the same.
import { afterEach, beforeEach, expect, test } from "bun:test";
import { chmodSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { join } from "node:path";

import type { Entries } from "../sdk/index.ts";
import cron from "../packages/cron/office.ts";
import { officeInfo, packageHost } from "./lifecycle-inputs.ts";
import { refreshOwner, refreshTimer, writeTimers } from "./timers.ts";
import { loadOffice } from "./office.ts";
import { officeCommand } from "./tool.ts";

let root: string;
let saved: NodeJS.ProcessEnv;

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "office-timer-bytes-"));
  saved = { ...process.env };
});

afterEach(() => {
  for (const key of Object.keys(process.env)) delete process.env[key];
  Object.assign(process.env, saved);
  rmSync(root, { recursive: true, force: true });
});

/** An office in a folder whose name needs escaping, a fake systemctl that records its calls, and exactly this environment. */
function prepare(mode: string) {
  const dir = join(root, "my office%1$x");
  const git = Bun.which("git");

  if (!git) throw new Error("git required");
  mkdirSync(join(root, "bin"), { recursive: true });
  mkdirSync(dir);
  symlinkSync(git, join(root, "bin/git"));
  writeFileSync(join(root, "bin/systemctl"), `#!/bin/sh\nprintf '%s\\n' "$*" >> '${root}/calls'\n`);
  chmodSync(join(root, "bin/systemctl"), 0o755);
  writeFileSync(join(dir, "office.yaml"), `name: bytes\nstate: ./state\nopencode: ${mode}\ngit: { name: Office Bot, email: bot@example.com }\n`);
  writeFileSync(join(dir, "run.sh"), "true\n");

  for (const key of Object.keys(process.env)) delete process.env[key];
  Object.assign(process.env, {
    PATH: `/opt/m/mise/installs/node/22/bin:${root}/bin:/usr/bin:/bin`, HOME: join(root, "home"), UNRELATED: "x", EXECUTOR_PORT: "42440",
    XDG_CONFIG_HOME: join(root, "home/.config"), OFFICE_SYSTEMD_USER_DIR: join(root, "units"),
  });

  return { dir, office: loadOffice(dir) };
}

const units = () => Object.fromEntries(readdirSync(join(root, "units")).sort().map(file => [file, readFileSync(join(root, "units", file), "utf8")]));

const header = "# Generated by `office up` for the bytes office. Don't edit: `office up` rewrites it and `office down` removes it.";

function service(description: string, words: string) {
  const dir = `${root}/my office%%1$x`;

  return `${header}
[Unit]
Description=office bytes: ${description}

[Service]
Type=oneshot
Environment="PATH=/opt/m/mise/shims:${root}/bin:/usr/bin:/bin"
Environment="HOME=${root}/home"
Environment="EXECUTOR_PORT=42440"
Environment="XDG_CONFIG_HOME=${root}/home/.config"
Environment="OFFICE_SYSTEMD_USER_DIR=${root}/units"
Environment="GIT_CONFIG_GLOBAL=${dir}/state/cron-gitconfig"
ExecStart="${officeCommand()}" "--office" "${dir.replaceAll("$", "$$$$")}" ${words}
`;
}

function timer(description: string, calendar: string) {
  return `${header}
[Unit]
Description=office bytes: ${description}

[Timer]
OnCalendar=${calendar}
Persistent=true

[Install]
WantedBy=timers.target
`;
}

test("a cron job's timer and service, its Git identity and its systemctl calls are the release's", async () => {
  const { dir, office } = prepare("{ mode: host, url: 'http://127.0.0.1:49374' }");
  const entries: Entries = () => [];

  // The cron package's up, for one of the office's own jobs, through the kernel's host helpers.
  await cron.up?.({ office: officeInfo(office), entries, settings: { jobs: { digest: { schedule: "15 6 * * 1", script: "run.sh" } } }, host: packageHost(office, "cron") });

  const unit = "office-bytes-cron-office.digest";

  expect(units()).toEqual({
    [`${unit}.service`]: service("office.digest", '"cron" "run" "office.digest"'),
    [`${unit}.timer`]: timer("office.digest", "Mon *-*-* 06:15:00 UTC"),
  });
  expect(readFileSync(join(root, "calls"), "utf8")).toBe(`--user show --property=FragmentPath --value ${unit}.timer
--user show --property=FragmentPath --value ${unit}.service
--user daemon-reload
--user enable --now ${unit}.timer
`);
  expect(readFileSync(join(dir, "state/cron-gitconfig"), "utf8")).toBe(`[include]
\tpath = ${root}/home/.config/git/config
\tpath = ${homedir()}/.gitconfig
[user]
\tname = Office Bot
\temail = bot@example.com
`);
});

test("the image refresh timer and service and their systemctl calls are the release's", () => {
  const { office } = prepare("container");

  writeTimers(office, refreshOwner, [refreshTimer(office)]);

  const unit = "office-bytes-refresh-image";

  expect(units()).toEqual({
    [`${unit}.service`]: service("office up --refresh", '"up" "--refresh"'),
    [`${unit}.timer`]: timer("office up --refresh", "Sun *-*-* 07:00:00 UTC"),
  });
  expect(readFileSync(join(root, "calls"), "utf8")).toBe(`--user show --property=FragmentPath --value ${unit}.timer
--user show --property=FragmentPath --value ${unit}.service
--user daemon-reload
--user enable --now ${unit}.timer
`);
});
