// `office apps deploy`: deploys the office's Executor apps from their folders through Executor's
// HTTP API with a token, then links the OpenCode account to every app that needs one.
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";

import { executorEnvFile, type Office, OfficeError, readEnvFile } from "../office.ts";
import { ports } from "./compose.ts";
import { adoptionMarker, adoptCatalog, catalogPlan, installedApps, installMissing } from "./catalog-apps.ts";

/** An app as Executor's API lists it, with only the fields the office reads. */
export type ExecutorApp = {
  id: string;
  slug: string;
  copiedFrom?: { name?: string | null } | null;
  activeVersion?: string;
  requirements?: { accounts?: { opencode?: { scope?: string } } };
};

type AccountLink = { requirement: string; account: { id: string; label: string } };

/** An app folder's package.json, with only the fields the office reads. */
type AppManifest = { dependencies?: Record<string, string>; executor?: { title?: string } };

export type AppFolder = { slug: string; dir: string; adopted: boolean };

/** The app folders: the root's executor/apps/* and each desk's. */
export function appFolders(office: Office): AppFolder[] {
  return ["", ...office.desks.map((desk) => desk.name)].flatMap((level) => {
    const dir = join(office.dir, level, "executor/apps");

    if (!existsSync(dir)) return [];

    return readdirSync(dir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory() && existsSync(join(dir, entry.name, "package.json")))
      .map((entry) => {
        const path = join(dir, entry.name);
        const marker = join(path, adoptionMarker);
        const adopted = existsSync(marker);

        if (adopted && (level !== "" || !office.catalogApps.includes(entry.name) || readFileSync(marker, "utf8").trim() !== entry.name)) {
          throw new OfficeError(`${marker}: an adopted app must be in executor/apps/<catalog-id> and declared in executor.catalog_apps`);
        }

        return { slug: entry.name, dir: path, adopted };
      });
  });
}

function readManifest(dir: string): AppManifest {
  return JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
}

/** The credential host of the OpenCode server as Executor reaches it, such as opencode:4096. */
function opencodeHost(office: Office): string {
  return new URL(office.opencode.containerUrl).host;
}

/**
 * An app's office.ts, which tells its OpenCode client where the server is for the office's mode.
 * The copy on disk holds container mode's values; the deployed copy always holds the current ones.
 */
function officeModule(office: Office): string {
  return `// Generated by \`office apps deploy\` for ${office.opencode.mode} mode (office.yaml's \`opencode:\`).
export const origin = ${JSON.stringify(office.opencode.containerUrl)};

/** The provider's credential host: Executor sends the password only to this host and port. */
export const host = ${JSON.stringify(opencodeHost(office))};

/** Session folders are under this one. */
export const officeDirectory = ${JSON.stringify(office.opencode.directory)};
`;
}

function sourceFiles(office: Office, folder: AppFolder) {
  return readdirSync(folder.dir, { recursive: true, withFileTypes: true })
    .flatMap((entry): { path: string; content: string; encoding?: "base64" }[] => {
      const path = relative(folder.dir, join(entry.parentPath, entry.name));

      if (!entry.isFile() || path.split("/").some(part => part === "node_modules" || part === ".git") || path === adoptionMarker) return [];

      if (path.startsWith("ui/public/")) return [{ path, content: readFileSync(join(folder.dir, path), "base64"), encoding: "base64" }];

      return [{ path, content: !folder.adopted && path === "office.ts" ? officeModule(office) : readFileSync(join(folder.dir, path), "utf8") }];
    });
}

export type Connection = { url: string; token: string };

/**
 * Executor's address and a token. In the container, OFFICE_EXECUTOR_URL and EXECUTOR_TOKEN are
 * set; on the host, Executor is on its published port and the token is the office's key, from its
 * state.
 */
export function connection(office: Office): Connection {
  const token = process.env.EXECUTOR_TOKEN ?? readEnvFile(executorEnvFile(office)).EXECUTOR_TOKEN;

  if (token === undefined) {
    // In the container the token comes from the environment, which the state file feeds.
    throw new OfficeError(`no Executor token: office setup saves the office's key in ${process.env.OFFICE_EXECUTOR_URL === undefined ? executorEnvFile(office) : "the office state's office-executor.env; then restart the container"}`);
  }

  return { url: process.env.OFFICE_EXECUTOR_URL ?? `http://localhost:${ports().executor}`, token };
}

/** A JSON request body. */
type Json = string | number | boolean | null | Json[] | { [key: string]: Json };

/** Calls Executor's HTTP API; the caller names the shape of the JSON it expects back. */
export type Call = <Result = null>(method: string, path: string, body?: Json) => Promise<Result>;

export function client({ url, token }: Connection): Call {
  return async (method, path, body) => {
    const authorization = `Bearer ${token}`;

    const response = await fetch(`${url}${path}`, {
      method,
      headers: body === undefined ? { authorization } : { authorization, "content-type": "application/json" },
      body: body === undefined ? undefined : JSON.stringify(body),
      signal: AbortSignal.timeout(300_000),
    });

    const text = await response.text();

    if (!response.ok) throw new OfficeError(`${method} ${path}: HTTP ${response.status} ${text}`);

    return text === "" ? null : JSON.parse(text);
  };
}

/**
 * The host an OpenCode account was connected for, from its label. Accounts keep the hosts they were
 * connected with and Executor's API doesn't show them, so the label records it; a label without one
 * predates host mode, when every account was the opencode container's.
 */
function accountHost(label: string): string {
  return / at (\S+)\)$/.exec(label)?.[1] ?? "opencode:4096";
}

/**
 * Links an OpenCode account to each app with an `opencode` app requirement that isn't linked to an
 * account for the server's current host. The account is created once, through the same connection
 * form a browser would fill, with the office's server password, which never passes through an
 * agent. Connecting it grants the host the deployed apps declare.
 */
async function linkOpencode(office: Office, call: Call, org: string, apps: ExecutorApp[]): Promise<string[]> {
  const password = process.env.OPENCODE_PASSWORD ?? readEnvFile(join(office.state, "secrets.env")).OPENCODE_PASSWORD;
  const host = opencodeHost(office);
  const lines: string[] = [];
  let account: string | undefined;

  const needing = apps.filter((app) => app.requirements?.accounts?.opencode?.scope === "app");
  const unlinked: ExecutorApp[] = [];

  // An app already linked to an account for this host supplies it for the others.
  for (const app of needing) {
    const links = await call<AccountLink[]>("GET", `/api/organizations/${org}/apps/${app.id}/accounts/app`);
    const link = links.find((entry) => entry.requirement === "opencode");

    if (link === undefined || accountHost(link.account.label) !== host) unlinked.push(app);
    else account ??= link.account.id;
  }

  for (const app of unlinked) {
    if (account === undefined) {
      if (password === undefined) throw new OfficeError(`OPENCODE_PASSWORD is missing from ${join(office.state, "secrets.env")}`);

      const started = await call<{ id: string }>("POST", `/api/organizations/${org}/apps/${app.id}/accounts/app/opencode/connections`, {});

      const created = await call<{ id: string }>("POST", `/api/organizations/${org}/connections/${started.id}/submit`, {
        method: "password",
        label: `OpenCode (${office.name} office at ${host})`,
        fields: { password },
      });

      account = created.id;
      lines.push(`connected the OpenCode account ${account} to ${app.slug}`);
    } else {
      await call("PUT", `/api/organizations/${org}/apps/${app.id}/accounts/app/opencode/${account}`);
      lines.push(`linked the OpenCode account ${account} to ${app.slug}`);
    }
  }

  return lines;
}

/** The TypeScript the apps are checked with, as the template's apps are. */
const typescriptVersion = "7.0.2";

/** Runs the Bun CLI: this executable acting as Bun, or Bun itself when run from a checkout. */
function bun(args: string[], cwd: string): void {
  execFileSync(process.execPath, args, { cwd, env: { ...process.env, BUN_BE_BUN: "1" }, stdio: ["ignore", "inherit", "inherit"] });
}

/**
 * Type-checks each app against the `apps` framework version Executor serves, with the packages
 * installed once per version under ~/.cache/office/. Throws, naming the app, on the first error,
 * before any app's package.json is changed.
 */
function typecheck(office: Office, folders: AppFolder[], version: string): void {
  const cache = join(process.env.XDG_CACHE_HOME ?? join(homedir(), ".cache"), "office", `apps-${version}`);
  const tsc = join(cache, "node_modules/typescript/bin/tsc");

  if (!existsSync(tsc)) {
    mkdirSync(cache, { recursive: true });
    writeFileSync(join(cache, "package.json"), `${JSON.stringify({ private: true, dependencies: { apps: version, typescript: typescriptVersion } }, null, 2)}\n`);
    bun(["install", "--silent"], cache);
  }

  for (const folder of folders) {
    const copy = mkdtempSync(join(tmpdir(), "office-app-"));

    try {
      cpSync(folder.dir, copy, { recursive: true, filter: (source) => !relative(folder.dir, source).split("/").includes("node_modules") });

      if (folder.adopted) {
        const modules = join(copy, "node_modules");

        mkdirSync(modules);
        symlinkSync(join(cache, "node_modules/apps"), join(modules, "apps"));

        for (const dep of Object.keys(readManifest(folder.dir).dependencies ?? {})) {
          if (dep === "apps" || !/^(?:@[\w.-]+\/)?[\w-][\w.-]*$/.test(dep)) continue;
          const path = join(folder.dir, "node_modules", dep);

          if (!existsSync(path)) continue;
          mkdirSync(dirname(join(modules, dep)), { recursive: true });
          symlinkSync(path, join(modules, dep));
        }
      } else {
        symlinkSync(join(cache, "node_modules"), join(copy, "node_modules"));
      }

      bun([tsc, "--ignoreConfig", "--noEmit", "--strict", "--skipLibCheck", "--module", "nodenext", "--moduleResolution", "nodenext", "--target", "es2022", "index.ts"], copy);
    } catch {
      throw new OfficeError(`${relative(office.dir, folder.dir)} doesn't type-check against apps@${version}; nothing was deployed${folder.adopted ? "; install any extra dependencies in the app folder before deploying" : ""}`);
    } finally {
      rmSync(copy, { recursive: true, force: true });
    }
  }
}

/** Sets each app's `apps` dependency to the version Executor serves, editing only that value. */
function matchFramework(office: Office, folders: AppFolder[], version: string): void {
  for (const folder of folders) {
    const path = join(folder.dir, "package.json");
    const before = readManifest(folder.dir).dependencies?.apps;

    if (before === version) continue;

    writeFileSync(path, readFileSync(path, "utf8").replace(/("apps"\s*:\s*")[^"]*(")/, `$1${version}$2`));
    console.log(`updated ${relative(office.dir, path)}: apps ${before ?? "(none)"} → ${version}`);
  }
}

/** The `apps` version each deployed app's source names, by slug, for `office check`. */
export async function deployedFrameworks(office: Office) {
  const call = client(connection(office));
  const { organization } = await call<{ organization: string }>("GET", "/api/context");
  const { version } = await call<{ version: string }>("GET", `/api/organizations/${organization}/framework/release`);
  const base = `/api/organizations/${organization}`;
  const apps = await installedApps(call, base);
  const folders = appFolders(office);
  const catalog = await catalogPlan(call, base, office.catalogApps, apps, folders);
  const slugs = new Set(folders.filter(folder => !folder.adopted).map((folder) => folder.slug));
  const deployed: { slug: string; apps: string | undefined }[] = [];

  for (const app of apps.filter((entry) => slugs.has(entry.slug))) {
    const source = await call<{ files: { path: string; content?: string }[] }>("GET", `/api/organizations/${organization}/apps/${app.id}/source`);
    const manifest = source.files.find((file) => file.path === "package.json")?.content;
    const parsed: AppManifest = manifest === undefined ? {} : JSON.parse(manifest);

    deployed.push({ slug: app.slug, apps: parsed.dependencies?.apps });
  }

  return { version, apps: deployed, catalog };
}

export async function adopt(office: Office, id: string) {
  await adoptCatalog(office, id, client(connection(office)), appFolders(office));
}

/**
 * Deploys every app in the office. Each app's `apps` dependency is first set to the framework
 * version Executor serves (after an Executor upgrade it moves) and every app is type-checked
 * against it, so nothing is deployed if any app would break.
 */
export async function deploy(office: Office): Promise<void> {
  const call = client(connection(office));
  const { organization } = await call<{ organization: string }>("GET", "/api/context");
  const { version } = await call<{ version: string }>("GET", `/api/organizations/${organization}/framework/release`);
  const folders = appFolders(office);

  const base = `/api/organizations/${organization}`;
  const existing = await installedApps(call, base);
  const plan = await catalogPlan(call, base, office.catalogApps, existing, folders);
  const authored = folders.filter(folder => !folder.adopted);

  for (const folder of authored) {
    if (existing.find(app => app.slug === folder.slug)?.copiedFrom?.name?.startsWith("@executor.sh/")) {
      throw new OfficeError(`${folder.slug}: local app would overwrite an installed catalog app; adopt it or rename the local folder`);
    }
  }

  if (folders.length) typecheck(office, folders, version);
  matchFramework(office, authored, version);
  await installMissing(call, base, plan, existing);
  const deployed: ExecutorApp[] = [];

  for (const folder of folders) {
    const manifest = readManifest(folder.dir);
    const files = sourceFiles(office, folder);
    let app = existing.find((entry) => entry.slug === folder.slug);

    if (app === undefined) {
      app = await call<ExecutorApp>("POST", `/api/organizations/${organization}/apps`, { name: manifest.executor?.title ?? folder.slug, files });
      console.log(`created ${app.slug} (${app.id})`);
    }

    const result = await call<{ app: ExecutorApp }>("POST", `/api/organizations/${organization}/apps/${app.id}/deploy`, { files });

    console.log(`deployed ${relative(office.dir, folder.dir)} → ${app.slug} (${app.id}) version ${result.app.activeVersion}`);

    if (!folder.adopted) deployed.push(result.app);
  }

  for (const line of await linkOpencode(office, call, organization, deployed)) console.log(line);
}
