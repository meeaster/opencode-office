// The cron package's timers through the compiled office: `office up` installs them through
// host.timers, `office check` compares them with the jobs as they are now, `office down` removes
// them through cron's `down` even with another package broken, and leaves them, saying so, when cron
// itself can't load. Timers the release before wrote are adopted unchanged. systemctl and Docker
// are stand-ins recording their calls; cron-container.e2e.test.ts covers container mode.
import { expect, test } from "bun:test";
import { mkdirSync, rmSync } from "node:fs";
import { join } from "node:path";
import { at, cronOffice, hostMode, mode, take, units } from "./office-up.fixture.ts";
import { definitionFixture, type DefinitionFixture } from "./package-definition.fixture.ts";
import { definitionText, writePackage } from "./test-package.ts";

const { exe, marker, write, read, fixture } = definitionFixture({ second: false });

/** The office's cron units' bytes, by file. */
function cronUnits(f: DefinitionFixture) {
  return Object.fromEntries(units(f).filter(file => file.includes("-cron-")).map(file => [file, read(join(f.home, "units", file))]));
}

/** Calls `office check` may make: systemd's reads and Compose's list of running services. */
const readCall = /^(systemctl --user show |docker compose -p \S+ -f \S+ ps --status running )/;

/**
 * `office check` in a host office: its cron package lines. The fixture's check exits 1 for two
 * failures unrelated to cron, always the same: Browse isn't installed and the machine gave no
 * consent; the test requires exactly those. Check is read-only: every unit file's bytes are the
 * same after it, every call it made is a read, and it read the state of each cron timer office wrote.
 */
function hostCheck(f: DefinitionFixture): string[] {
  const files = () => Object.fromEntries(units(f).map(file => [file, read(join(f.home, "units", file))]));
  const before = files();

  take(f);
  const output = f.cli(1, "check");
  const calls = take(f);

  expect(files()).toEqual(before);
  expect(calls.filter(line => !readCall.test(line))).toEqual([]);

  for (const [file, text] of Object.entries(before)) {
    if (!file.startsWith(`office-${f.dir.split("/").at(-1)}-cron-`) || !file.endsWith(".timer") || !text.startsWith("# Generated by `office up`")) continue;
    expect(calls).toContain(`systemctl --user show ${file} --property=ActiveState,NextElapseUSecRealtime,LastTriggerUSec`);
  }

  const lines = output.split("\n");

  expect(lines.filter(line => line.startsWith("FAIL ") && !line.startsWith("FAIL package cron:")).map(line => line.slice(0, line.indexOf(":")))).toEqual(["FAIL package browser", "FAIL machine"]);

  return lines.filter(line => /^(FAIL|WARN) package cron:/.test(line));
}

const ids = ["office.mine", "package.office.update-references", "package.report.digest"];

const calendars = new Map([["office.mine", "*-*-* 06:15:00 UTC"], ["package.office.update-references", "*-*-* 06:00:00 UTC"], ["package.report.digest", "Mon *-*-* 07:00:00 UTC"]]);

/**
 * A timer and its service as the release before cron became a package wrote them, for this
 * fixture's office, launcher and environment: what office up then ran with, filtered as it did.
 */
function released(f: DefinitionFixture, name: string, id: string) {
  const header = `# Generated by \`office up\` for the ${name} office. Don't edit: \`office up\` rewrites it and \`office down\` removes it.`;
  const description = `Description=office ${name}: ${id}`;
  const kept = ["HOME", "TMPDIR", "OFFICE_MACHINE_RECORD", "OFFICE_MISE_CONFIG_DIR", "OFFICE_MACHINE_DIR", "OFFICE_APP_CONFIG_DIR", "OFFICE_APP_PANELS_DIR", "OFFICE_SYSTEMD_USER_DIR", "EXECUTOR_PORT", "OPENCODE_PORT"];
  const env: Record<string, string> = f.env;
  const environment = [`PATH=${f.env.PATH}`, ...kept.map(key => `${key}=${env[key]}`)];

  return {
    service: [header, "[Unit]", description, "", "[Service]", "Type=oneshot", ...environment.map(variable => `Environment="${variable}"`), `ExecStart=${[exe, "--office", f.dir, "cron", "run", id].map(word => `"${word}"`).join(" ")}`, ""].join("\n"),
    timer: [header, "[Unit]", description, "", "[Timer]", `OnCalendar=${calendars.get(id)}`, "Persistent=true", "", "[Install]", "WantedBy=timers.target", ""].join("\n"),
  };
}

test("timers installed by the release before are adopted unchanged: nothing stopped, disabled or removed, each enabled; down then clears them", () => {
  const f = fixture("adopt");
  cronOffice(f, write);
  mode(f, write, hostMode);
  f.cli(0, "sync", "--packages");

  for (const id of ids) {
    const unit = released(f, "adopt", id);

    write(join(f.home, `units/office-adopt-cron-${id}.service`), unit.service);
    write(join(f.home, `units/office-adopt-cron-${id}.timer`), unit.timer);
  }

  const before = cronUnits(f);

  expect(Object.keys(before)).toHaveLength(6);
  take(f);
  f.cli(0, "up");
  const calls = take(f);

  expect(cronUnits(f)).toEqual(before);
  expect(calls.filter(line => /^systemctl --user (disable|stop) .*-cron-/.test(line))).toEqual([]);
  expect(calls.find(line => line.startsWith("systemctl --user enable --now "))?.split(" ").slice(4).sort()).toEqual(ids.map(id => `office-adopt-cron-${id}.timer`));

  f.cli(0, "down");
  const down = take(f);

  expect(units(f).filter(file => file.includes("-cron-"))).toEqual([]);
  expect(at(down, /^systemctl --user disable --now .*office-adopt-cron-/)).toBeLessThan(at(down, /^docker compose -p office-adopt .* down/));
}, 60_000);

test("up installs one persistent timer per job and touches no other unit; check compares; sync changes none; a removed job's timer goes", () => {
  const f = fixture("cronhost");
  cronOffice(f, write);
  mode(f, write, hostMode);
  const config = join(f.dir, "office.yaml");

  const others = {
    "office-cronhost-opencode.service": "# Generated by office for cronhost: managed OpenCode. Do not edit.\n",
    "office-cronhost-pkg-notes.serve.service": "# office package services: /elsewhere\n",
    "office-other-cron-package.office.update-references.timer": "# Generated by `office up` for the other office. Don't edit\n",
    "office-cronhost-cron-x.timer": "operator's file\n",
  };

  for (const [file, text] of Object.entries(others)) write(join(f.home, "units", file), text);
  f.cli(0, "sync");
  take(f);
  expect(f.cli(0, "up")).toContain("package cron: timer office-cronhost-cron-package.report.digest: Mon *-*-* 07:00:00 UTC, package.report.digest");

  for (const id of ids) {
    expect(read(join(f.home, `units/office-cronhost-cron-${id}.timer`))).toContain(`\nOnCalendar=${calendars.get(id)}\nPersistent=true\n`);
    expect(read(join(f.home, `units/office-cronhost-cron-${id}.service`))).toContain(`ExecStart="${exe}" "--office" "${f.dir}" "cron" "run" "${id}"`);
  }

  expect(units(f).filter(file => file.includes("-cron-"))).toHaveLength(8);
  const installed = cronUnits(f);

  expect(hostCheck(f)).toEqual([]);

  // Stopped by hand: named as inactive.
  mkdirSync(join(f.home, "inactive"), { recursive: true });
  write(join(f.home, "inactive/office-cronhost-cron-office.mine.timer"), "");
  expect(hostCheck(f)).toEqual(["FAIL package cron: office-cronhost-cron-office.mine.timer is inactive (run office up)"]);
  rmInactive(f);

  // A job's service left without its timer: the timer is missing, not inactive.
  const mine = join(f.home, "units/office-cronhost-cron-office.mine.timer");

  rmSync(mine);
  expect(hostCheck(f)).toEqual(["FAIL package cron: office-cronhost-cron-office.mine.timer is missing (run office up)"]);
  write(mine, installed["office-cronhost-cron-office.mine.timer"]);

  // A changed schedule and a disabled job: sync changes no timer, check reports both.
  const synced = read(config);

  write(config, synced.replace("overrides: {", "overrides: {package.office.update-references: {schedule: '0 5 * * *'}, package.report.digest: {enabled: false}, "));
  f.cli(0, "sync");
  expect(cronUnits(f)).toEqual(installed);
  expect(hostCheck(f).sort()).toEqual([
    "FAIL package cron: office-cronhost-cron-package.office.update-references.timer: its installed schedule differs from *-*-* 05:00:00 UTC (run office up)",
    "FAIL package cron: office-cronhost-cron-package.report.digest.service is no longer wanted: no job package.report.digest applies (office up removes it)",
    "FAIL package cron: office-cronhost-cron-package.report.digest.timer is no longer wanted: no job package.report.digest applies (office up removes it)",
  ]);

  // Deselected, its job's timer goes at the next up; the others are unchanged.
  write(config, synced.replace("  - name: report\n", ""));
  f.cli(0, "sync");
  take(f);
  f.cli(0, "up");
  expect(take(f).some(line => line.startsWith("systemctl --user disable --now ") && line.includes("office-cronhost-cron-package.report.digest.timer"))).toBe(true);
  const kept = cronUnits(f);

  expect(Object.keys(kept).sort()).toEqual(Object.keys(installed).filter(file => !file.includes("report.digest")).sort());

  for (const file of Object.keys(kept).filter(file => file !== "office-cronhost-cron-x.timer")) expect(kept[file]).toBe(installed[file]);

  // Someone else's file at a wanted name: up refuses naming it, and down leaves it.
  const wanted = join(f.home, "units/office-cronhost-cron-office.mine.timer");

  write(wanted, "the operator's own\n");
  expect(f.cli(1, "up")).toContain(`${wanted} is not an office-generated cron unit; office leaves it alone`);
  f.cli(0, "down");
  expect(read(wanted)).toBe("the operator's own\n");
  expect(units(f).filter(file => file.startsWith("office-cronhost-cron-")).sort()).toEqual(["office-cronhost-cron-office.mine.timer", "office-cronhost-cron-x.timer"]);

  for (const [file, text] of Object.entries(others)) expect(read(join(f.home, "units", file))).toBe(text);
}, 60_000);

function rmInactive(f: DefinitionFixture) {
  Bun.spawnSync(["rm", "-r", join(f.home, "inactive")]);
}

test("down with a broken package, and no temporary folder, removes cron's timers and exits 1 naming it; with cron itself unloadable its timers stay, and down says so", () => {
  const f = fixture("crondown");
  cronOffice(f, write);
  mode(f, write, hostMode);
  f.cli(0, "sync");
  f.cli(0, "up");
  expect(units(f).filter(file => file.includes("-cron-"))).toHaveLength(6);
  const report = join(f.dir, "packages/report/office.ts");

  writePackage(report, `${marker} throw Error("broken report");`);
  take(f);
  // The shutdown reader needs no temporary folder.
  const tmp = f.env.TMPDIR;
  f.env.TMPDIR = join(f.home, "missing");
  const broken = f.cli(1, "down");
  f.env.TMPDIR = tmp;

  expect(broken).toContain("package report: left out of shutdown, so what it installed, such as its timers, stays installed: packages/report/office.ts: broken report");
  expect(broken).toContain("office: the office's own shutdown completed, but not every package's (above)");
  expect(units(f).filter(file => file.includes("-cron-"))).toEqual([]);
  at(take(f), /^docker compose -p office-crondown .* down/);

  // Fixed and up again; then cron's own copy fails its check.
  writePackage(report, definitionText('{setup(c){c.add({id:"cron.jobs",parse:v=>v},{name:"digest",schedule:"0 7 * * MON",script:"digest.sh"})}}'));
  f.cli(0, "up");
  const installed = cronUnits(f);
  const copy = join(f.dir, ".office/packages/cron/schedule.ts");

  write(copy, `${read(copy)}\n`);
  take(f);
  const unloadable = f.cli(1, "down");

  expect(unloadable).toContain("package cron: left out of shutdown, so what it installed, such as its timers, stays installed: package files edited: schedule.ts (edited)");
  expect(cronUnits(f)).toEqual(installed);
  at(take(f), /^docker compose -p office-crondown .* down/);
}, 60_000);
