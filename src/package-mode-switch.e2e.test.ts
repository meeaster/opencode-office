// Switching an office between host and container mode never runs two schedulers: the old one is
// stopped before the new one starts, asserted from the order of the recorded Docker and systemctl
// calls in one log, with a test package's timers beside the cron package's.
import { expect, test } from "bun:test";
import { rmSync } from "node:fs";
import { join } from "node:path";
import { at, hostMode as host, mode as setMode, rig, take, units } from "./office-up.fixture.ts";
import { definitionFixture, type DefinitionFixture } from "./package-definition.fixture.ts";
import { definitionText, writePackage } from "./test-package.ts";

const { write, read, fixture } = definitionFixture({ second: false });

/** The rig, and a test package that sets its timer on a host and none in the container. */
function prepare(f: DefinitionFixture) {
  const config = join(f.dir, "office.yaml");

  // The template's packages list is last: the entry joins it.
  write(config, `${read(config)}  - name: notes\n`);
  rig(f, write);
  writePackage(join(f.dir, "packages/notes/office.ts"), definitionText('{up({office, host}) { return office.mode === "container" ? [] : host.timers.set([{id: "digest", calendar: "*-*-* 06:00:00 UTC", run: ["notes"]}]) }}'));
}

test("host to container: every host timer is stopped and removed before Compose starts the container, also when starting it fails", () => {
  const f = fixture("tocontainer");
  prepare(f);
  setMode(f, write, host);
  f.cli(0, "sync", "--packages");
  f.cli(0, "up");
  const installed = units(f);
  expect(installed).toContain("office-tocontainer-notes-digest.timer");
  expect(installed).toContain("office-tocontainer-cron-package.office.update-references.timer");
  take(f);

  setMode(f, write, "opencode: container");
  write(join(f.home, "compose-fails"), "");
  f.cli(1, "up");
  const calls = take(f);
  const stopped = at(calls, /^systemctl --user disable --now .*office-tocontainer-notes-digest\.timer/);
  expect(calls[stopped]).toContain("office-tocontainer-cron-package.office.update-references.timer");
  expect(stopped).toBeLessThan(at(calls, /^docker compose -p office-tocontainer .* up -d /));
  expect(units(f)).toEqual(["office-tocontainer-refresh-image.service", "office-tocontainer-refresh-image.timer"]);

  // Without a user manager and no host timers left, the refresh timer is only a warning; Compose starts.
  rmSync(join(f.home, "compose-fails"));
  rmSync(join(f.home, "units"), { recursive: true });
  write(join(f.home, "no-systemd"), "");
  expect(f.cli(0, "up")).toContain("no systemd user manager, so nothing refreshes the opencode image's Debian packages weekly");
  at(take(f), /^docker compose -p office-tocontainer .* up -d /);

  // A host timer that can't be stopped is named, and the container's scheduler doesn't start.
  for (const suffix of ["timer", "service"]) write(join(f.home, `units/office-tocontainer-notes-digest.${suffix}`), "# Generated by `office up` for the tocontainer office. Don't edit\n");
  const refused = f.cli(1, "up");
  expect(refused).toMatch(/couldn't stop the host timers office-tocontainer-notes-digest\.(timer|service), office-tocontainer-notes-digest\.(timer|service), so the container's scheduler doesn't start beside them/);
  expect(take(f).some(line => / up -d /.test(line))).toBe(false);
  expect(units(f)).toContain("office-tocontainer-notes-digest.timer");
}, 60_000);

test("container to host: the OpenCode container is stopped and the image refresh timer removed before any timer is enabled", () => {
  const f = fixture("tohost");
  prepare(f);
  f.cli(0, "sync", "--packages");
  f.cli(0, "up");
  expect(units(f)).toEqual(["office-tohost-refresh-image.service", "office-tohost-refresh-image.timer"]);
  take(f);

  setMode(f, write, host);
  f.cli(0, "up");
  const calls = take(f);
  const container = at(calls, /^docker compose -p office-tohost .* rm --stop --force opencode$/);
  const refresh = at(calls, /^systemctl --user disable --now office-tohost-refresh-image\.timer$/);
  const enabled = at(calls, /^systemctl --user enable --now /);
  expect(container).toBeLessThan(refresh);
  expect(refresh).toBeLessThan(enabled);
  const enabling = calls.filter(line => line.startsWith("systemctl --user enable --now")).join("\n");

  expect(enabling).toContain("office-tohost-notes-digest.timer");
  expect(enabling).toContain("office-tohost-cron-package.office.update-references.timer");
  expect(units(f).some(file => file.includes("refresh-image"))).toBe(false);
  expect(units(f)).toContain("office-tohost-notes-digest.timer");
}, 60_000);
