// The office's systemd user timers, each with Persistent=true, so systemd runs one missed while the
// computer was off. In host mode each applicable YAML job becomes a timer whose service runs
// `office cron run <job-id>` from the office root. In container
// mode the only one runs `office up --refresh` weekly, which the container can't do itself: it
// rebuilds the opencode image with current Debian packages and restarts the container. The units
// are named office-<office>-<job>, written by `office up` and removed by `office down`. With a
// git identity in office.yaml, each service's GIT_CONFIG_GLOBAL is a generated file that includes
// the user's global git config and then sets that identity, so the office's jobs commit as the
// office without the host's global identity changing; a repository's own config still overrides.
import { execFileSync } from "node:child_process";
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

import { type Office, OfficeError } from "../office.ts";
import { officeCommand } from "../tool.ts";
import type { CronJob } from "./jobs.ts";
import type { ScheduleFields } from "./schedule.ts";
import { say } from "../report/index.ts";

/** A systemd timer: its unit name, OnCalendar value, a description, and the `office` arguments its service runs. */
type Timer = { unit: string; calendar: string; description: string; args: string[] };

export const unitDirVariable = "OFFICE_SYSTEMD_USER_DIR";

export function unitDir(): string {
  return process.env[unitDirVariable] ?? join(process.env.XDG_CONFIG_HOME ?? join(homedir(), ".config"), "systemd/user");
}

// Marks a unit as generated, so `office up` and `office down` only touch their own files.
const marker = "# Generated by `office up`";

const weekdays = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];

function systemctl(args: string[], { capture = false } = {}): string {
  return execFileSync("systemctl", ["--user", ...args], { encoding: "utf8", stdio: capture ? ["ignore", "pipe", "pipe"] : "inherit" }) ?? "";
}

/** Whether this machine has a systemd user manager to run timers; macOS and some WSL setups don't. */
export function hasSystemd(): boolean {
  try {
    execFileSync("systemctl", ["--user", "show", "--property=Version"], { stdio: "ignore" });

    return true;
  } catch {
    return false;
  }
}

function values(set: Set<number> | undefined, format: (value: number) => string = String): string {
  return set === undefined ? "*" : [...set].sort((a, b) => a - b).map(format).join(",");
}

function onCalendar({ minute, hour, day, month, weekday }: ScheduleFields): string {
  const two = (number: number) => String(number).padStart(2, "0");
  const date = `*-${values(month, two)}-${values(day, two)}`;
  const time = `${values(hour, two)}:${values(minute, two)}:00`;

  return `${weekday === undefined ? "" : `${values(weekday, (index: number) => weekdays[index])} `}${date} ${time} UTC`;
}

// systemd splits these lines on spaces and expands % specifiers, and ExecStart also $ variables.
function quoted(text: string): string {
  return `"${text.replaceAll("\\", "\\\\").replaceAll('"', '\\"').replaceAll("\r", "\\r").replaceAll("\n", "\\n").replaceAll("%", "%%")}"`;
}

export function argument(text: string): string {
  // "$$$$" is the replacement pattern for a literal "$$", systemd's escape for "$".
  return quoted(text).replaceAll("$", "$$$$");
}

/**
 * The PATH `office up` ran with, so jobs find mise and the tools they call (and Bun, for a
 * checkout's launcher), without mise's per-version install folders: an upgrade removes those, and
 * mise's shims resolve each tool for the folder a job runs in.
 */
function jobPath(): string {
  const dirs: string[] = [];

  for (const dir of (process.env.PATH ?? "/usr/bin:/bin").split(":")) {
    const installs = dir.indexOf("/mise/installs/");
    // `mise activate` puts install folders on PATH rather than the shims, so each becomes the
    // shims folder of the same mise, which then provides those tools, such as sops for `office up`.
    const entry = installs === -1 ? dir : `${dir.slice(0, installs)}/mise/shims`;

    if (!dirs.includes(entry)) dirs.push(entry);
  }

  return dirs.join(":");
}

/** The ID, not the script's basename, determines the persistent timer's name. */
export function cronTimers(office: Office, jobs: CronJob[]): Timer[] {
  return jobs.map((job) => {
    const unit = `office-${office.name}-cron-${job.id}`;

    if (`${unit}.service`.length > 255) throw new OfficeError(`cron ${job.id}: systemd unit name is too long; shorten the office or package name`);

    return { unit, calendar: onCalendar(job.fields), description: job.id, args: ["cron", "run", job.id] };
  });
}

/** Container mode's weekly refresh of the opencode image, Sundays after the daily jobs. */
export function refreshTimer(office: Office): Timer {
  return { unit: `office-${office.name}-refresh-image`, calendar: "Sun *-*-* 07:00:00 UTC", description: "office up --refresh", args: ["up", "--refresh"] };
}

/**
 * The environment `office up` ran with that the office's commands read: PATH, and the ports, so a
 * timer brings up an office started on other ports (EXECUTOR_PORT=42440) on the same ones.
 */
function jobEnvironment(): string[] {
  const context = new Set([
    "HOME", "XDG_CONFIG_HOME", "XDG_DATA_HOME", "XDG_STATE_HOME", "XDG_CACHE_HOME", "TMPDIR",
    "MISE_CONFIG_DIR", "MISE_DATA_DIR", "MISE_STATE_DIR", "MISE_CACHE_DIR",
    unitDirVariable, "OFFICE_MACHINE_DIR", "OFFICE_MACHINE_RECORD", "OFFICE_MISE_CONFIG_DIR",
    "OFFICE_APP_CONFIG_DIR", "OFFICE_APP_PANELS_DIR",
  ]);

  const environment = [`PATH=${jobPath()}`];

  for (const [key, value] of Object.entries(process.env)) {
    if (value !== undefined && (key.endsWith("_PORT") || context.has(key))) environment.push(`${key}=${value}`);
  }

  return environment;
}

function generatedUnits(office: Office): string[] {
  const dir = unitDir();

  if (!existsSync(dir)) return [];

  return readdirSync(dir, { withFileTypes: true }).flatMap((file) => {
    if (!file.isFile() || !file.name.startsWith(`office-${office.name}-`) || !/\.(service|timer)$/.test(file.name)) return [];

    return readFileSync(join(dir, file.name), "utf8").startsWith(`${marker} for the ${office.name} office. `) ? [file.name] : [];
  });
}

export function requireLocalUnit(file: string): void {
  const fragment = systemctl(["show", "--property=FragmentPath", "--value", file], { capture: true }).trim();

  if (fragment !== "" && fragment !== join(unitDir(), file)) throw new OfficeError(`${file} is loaded from ${fragment}; office leaves it alone`);
}

/**
 * The global git config the office's jobs run with: the user's own (both places git reads it
 * from, or GIT_CONFIG_GLOBAL's file), then the office's identity. Undefined without an identity.
 */
function jobGitConfig(office: Office): string | undefined {
  if (office.git?.name === undefined || office.git.email === undefined) return undefined;

  const path = join(office.state, "cron-gitconfig");
  const own = process.env.GIT_CONFIG_GLOBAL === undefined ? [join(process.env.XDG_CONFIG_HOME ?? join(homedir(), ".config"), "git/config"), join(homedir(), ".gitconfig")] : [process.env.GIT_CONFIG_GLOBAL];
  const set = (...args: string[]) => execFileSync("git", ["config", "--file", path, ...args], { stdio: "ignore" });

  mkdirSync(office.state, { recursive: true });
  rmSync(path, { force: true });

  // Git skips an included file that doesn't exist.
  for (const file of own) set("--add", "include.path", file);

  set("user.name", office.git.name);
  set("user.email", office.git.email);

  return path;
}

/** Writes the office's timers, removes generated ones not among them, and starts them. */
export function installTimers(office: Office, wanted: Timer[]): void {
  const dir = unitDir();
  const generated = generatedUnits(office);
  const keep = wanted.flatMap(({ unit }) => [`${unit}.timer`, `${unit}.service`]);

  for (const name of keep) {
    if (!generated.includes(name) && lstatSync(join(dir, name), { throwIfNoEntry: false }) !== undefined) {
      throw new OfficeError(`${join(dir, name)} is not an office-generated cron unit; office leaves it alone`);
    }

    requireLocalUnit(name);
  }

  stopTimers(generated.filter((file) => !keep.includes(file)));

  if (wanted.length === 0) {
    if (generated.length > 0) systemctl(["daemon-reload"]);

    return;
  }

  const gitConfig = jobGitConfig(office);
  const environment = jobEnvironment();
  const header = `${marker} for the ${office.name} office. Don't edit: \`office up\` rewrites it and \`office down\` removes it.`;

  mkdirSync(dir, { recursive: true });

  for (const timer of wanted) {
    const description = `Description=office ${office.name}: ${timer.description}`;

    writeFileSync(
      join(dir, `${timer.unit}.service`),
      [
        header,
        "[Unit]",
        description,
        "",
        "[Service]",
        "Type=oneshot",
        // Pass the office as an argument instead: WorkingDirectory= does not use ExecStart quoting.
        ...environment.map((variable) => `Environment=${quoted(variable)}`),
        ...(gitConfig === undefined ? [] : [`Environment=${quoted(`GIT_CONFIG_GLOBAL=${gitConfig}`)}`]),
        `ExecStart=${[officeCommand(), "--office", office.dir, ...timer.args].map(argument).join(" ")}`,
        "",
      ].join("\n"),
    );

    writeFileSync(
      join(dir, `${timer.unit}.timer`),
      [header, "[Unit]", description, "", "[Timer]", `OnCalendar=${timer.calendar}`, "Persistent=true", "", "[Install]", "WantedBy=timers.target", ""].join("\n"),
    );
  }

  systemctl(["daemon-reload"]);

  if (wanted.length > 0) systemctl(["enable", "--now", ...wanted.map((timer) => `${timer.unit}.timer`)]);

  for (const timer of wanted) say(`timer ${timer.unit}: ${timer.calendar}, ${timer.description}`);
}

function stopTimers(files: string[]): void {
  const timerUnits = files.filter((file) => file.endsWith(".timer"));
  const services = files.filter((file) => file.endsWith(".service"));

  for (const file of files) requireLocalUnit(file);

  if (timerUnits.length > 0) systemctl(["disable", "--now", ...timerUnits]);

  if (services.length > 0) systemctl(["stop", ...services]);

  for (const file of files) rmSync(join(unitDir(), file));

  if (files.length > 0) say(`removed ${files.join(", ")}`);
}

/** Stops and removes every timer `office up` generated for the office. */
export function removeTimers(office: Office): void {
  const files = generatedUnits(office);

  // The machine of an office without timers may have no systemd.
  if (files.length === 0) return;

  stopTimers(files);
  systemctl(["daemon-reload"]);
}

/** Each timer's state, for `office check`. */
export function timerStates(expected: Timer[]): (Timer & { active: boolean; matches: boolean; next: string; last: string })[] {
  return expected.map((timer) => {
    const path = join(unitDir(), `${timer.unit}.timer`);
    const exists = lstatSync(path, { throwIfNoEntry: false })?.isFile() ?? false;
    const shown = exists ? systemctl(["show", `${timer.unit}.timer`, "--property=ActiveState,NextElapseUSecRealtime,LastTriggerUSec"], { capture: true }) : "";
    const property = (name: string) => new RegExp(`^${name}=(.*)$`, "m").exec(shown)?.[1] ?? "";
    const matches = exists && readFileSync(path, "utf8").includes(`\nOnCalendar=${timer.calendar}\nPersistent=true\n`);

    return { ...timer, active: property("ActiveState") === "active", matches, next: property("NextElapseUSecRealtime"), last: property("LastTriggerUSec") };
  });
}

export function staleTimerUnits(office: Office, wanted: Timer[]): string[] {
  const keep = new Set(wanted.flatMap(({ unit }) => [`${unit}.timer`, `${unit}.service`]));

  return generatedUnits(office).filter((file) => !keep.has(file));
}
