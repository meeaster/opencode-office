// Deploys the office's Executor apps through the runtime's Executor access: it builds every app's
// upload and compares it with the active deployment, type-checks only the changed apps against the
// `apps` framework Executor serves, and writes nothing (no manifest edit, catalog install, create,
// deploy or link) unless every one passes. Then it links OpenCode accounts and asks for the
// contributed apps' own accounts.
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";

import type { ExecutorAccess } from "@office/sdk";
import { catalogPlan, type ExecutorApp, frameworkVersion, installedApps, installMissing, organizationPath, unexpected } from "./catalog.ts";
import { adoptionMarker, type AppFolder, readManifest } from "./inventory.ts";

/** The generated module that gives a contributed app its office's resolved settings. */
const packageModulePath = "package.ts";

type OpenCode = ExecutorAccess["opencode"];

/**
 * A root app's office.ts, which tells its OpenCode client where the server is for the office's
 * mode. The copy on disk holds container mode's values; the deployed copy always holds the current ones.
 */
export function officeModule(opencode: OpenCode): string {
  return `// Generated by \`office apps deploy\` for ${opencode.mode} mode (office.yaml's \`opencode:\`).
export const origin = ${JSON.stringify(opencode.url)};

/** The provider's credential host: Executor sends the password only to this host and port. */
export const host = ${JSON.stringify(new URL(opencode.url).host)};

/** Session folders are under this one. */
export const officeDirectory = ${JSON.stringify(opencode.directory)};
`;
}

/**
 * A contributed app's package.ts: its package's settings as office.yaml resolves them, and the
 * office's mode. The copy in the package holds the defaults, with the same shape, for type-checking.
 */
export function packageModule(opencode: OpenCode, contributor: NonNullable<AppFolder["contributor"]>): string {
  return `// Generated by \`office apps deploy\` from the ${contributor.name} package's settings in office.yaml.
export const settings = ${JSON.stringify(contributor.settings, null, 2)};

/** Where the office's OpenCode server runs: "host" or "container". */
export const opencode = ${JSON.stringify(opencode.mode)};
`;
}

/** A package.json with its `apps` dependency set to `version`, editing only that value. */
function withFramework(manifest: string, version: string): string {
  return manifest.replace(/("apps"\s*:\s*")[^"]*(")/, `$1${version}$2`);
}

/**
 * The text deploy sends for a file of a folder, which differs from the disk for generated files and
 * for a manifest naming another `apps` version.
 */
function deployedText(opencode: OpenCode, folder: AppFolder, path: string, version: string): string {
  const disk = readFileSync(join(folder.dir, path), "utf8");

  if (folder.adopted) return disk;

  // An office app's package.json as deploy will have set its framework version.
  if (path === "package.json") return folder.contributor !== undefined || readManifest(folder.dir).dependencies?.apps !== version ? withFramework(disk, version) : disk;

  if (folder.contributor !== undefined) return path === packageModulePath ? packageModule(opencode, folder.contributor) : disk;

  return path === "office.ts" ? officeModule(opencode) : disk;
}

type UploadFile = { path: string; content: string; encoding?: "base64" };

function sourceFiles(opencode: OpenCode, folder: AppFolder, version: string): UploadFile[] {
  return readdirSync(folder.dir, { recursive: true, withFileTypes: true })
    .flatMap((entry): UploadFile[] => {
      const path = relative(folder.dir, join(entry.parentPath, entry.name));

      if (!entry.isFile() || path.split("/").some(part => part === "node_modules" || part === ".git") || path === adoptionMarker) return [];

      if (path.startsWith("ui/public/")) return [{ path, content: readFileSync(join(folder.dir, path), "base64"), encoding: "base64" }];

      return [{ path, content: deployedText(opencode, folder, path, version) }];
    });
}

type RunningFile = { path: string; content?: string; encoding?: string; object?: string; size?: number };

/** Compares the upload with the running files. Public assets can come back as Git blob IDs. */
async function matchesActiveSource(executor: ExecutorAccess, appPath: string, version: string, files: UploadFile[]): Promise<boolean> {
  const path = `${appPath}/source?version=${encodeURIComponent(version)}`;
  const source = await executor.request<{ files?: RunningFile[] } | null>("GET", path);

  if (typeof source !== "object" || source === null || !Array.isArray(source.files)) throw unexpected(path);
  const running = new Map(source.files.map(file => [file.path, file]));

  return running.size === files.length && files.every(file => {
    const other = running.get(file.path);

    if (!other) return false;

    if (typeof other.content === "string" && other.encoding === file.encoding) return other.content === file.content;

    const bytes = Buffer.from(file.content, file.encoding ?? "utf8");

    if (typeof other.content === "string") return bytes.equals(Buffer.from(other.content, other.encoding === "base64" ? "base64" : "utf8"));

    return other.size === bytes.length && other.object === createHash("sha1").update(`blob ${bytes.length}\0`).update(bytes).digest("hex");
  });
}

/** The TypeScript the apps are checked with, as the template's apps are. */
const typescriptVersion = "7.0.2";

/** What deploy reports while it works and whether it shows the type-checker's output as it runs. */
export type Reporting = { line(text: string): void; progress(text: string): void; verbose: boolean };

/**
 * Runs Bun: the process running this package, which is the office executable acting as Bun
 * (`BUN_BE_BUN`), or Bun itself from a checkout. Its output streams to standard error with
 * `--verbose`; otherwise it is kept and shown only when Bun fails. Throws unless Bun succeeds.
 */
async function bun(args: string[], cwd: string, reporting: Reporting): Promise<void> {
  const child = Bun.spawn([process.execPath, ...args], { cwd, env: { ...process.env, BUN_BE_BUN: "1" }, stdin: "ignore", stdout: "pipe", stderr: "pipe" });
  const kept: string[] = [];

  const emit = (line: string) => reporting.verbose ? console.error(line) : kept.push(line);

  const drain = async (stream: ReadableStream<Uint8Array>) => {
    const decoder = new TextDecoder();
    let rest = "";

    for await (const chunk of stream) {
      const lines = (rest + decoder.decode(chunk, { stream: true })).split("\n");

      rest = lines.pop() ?? "";
      lines.forEach(emit);
    }

    if (rest !== "") emit(rest);
  };

  const [status] = await Promise.all([child.exited, drain(child.stdout), drain(child.stderr)]);

  if (status !== 0) {
    for (const line of kept.slice(-60)) console.error(line);

    throw new Error(`${["bun", ...args].join(" ")} exited with status ${status}`);
  }
}

/**
 * Type-checks each folder against `apps@version`, with the packages installed once per version under
 * ~/.cache/office/. Throws naming every folder that fails, after trying them all.
 */
async function typecheck(opencode: OpenCode, folders: readonly AppFolder[], version: string, reporting: Reporting): Promise<void> {
  const cache = join(process.env.XDG_CACHE_HOME ?? join(homedir(), ".cache"), "office", `apps-${version}`);
  const tsc = join(cache, "node_modules/typescript/bin/tsc");
  const failed: AppFolder[] = [];

  if (!existsSync(tsc)) {
    mkdirSync(cache, { recursive: true });
    writeFileSync(join(cache, "package.json"), `${JSON.stringify({ private: true, dependencies: { apps: version, typescript: typescriptVersion } }, null, 2)}\n`);
    reporting.progress(`installing apps@${version} and TypeScript to type-check the apps`);
    await bun(["install", "--silent"], cache, reporting);
  }

  for (const folder of folders) {
    const copy = mkdtempSync(join(tmpdir(), "office-app-"));

    try {
      cpSync(folder.dir, copy, { recursive: true, filter: (source) => !relative(folder.dir, source).split("/").includes("node_modules") });

      // A contributed app is checked with the settings it will be deployed with.
      if (folder.contributor !== undefined) writeFileSync(join(copy, packageModulePath), packageModule(opencode, folder.contributor));

      if (folder.adopted) {
        const modules = join(copy, "node_modules");

        mkdirSync(modules);
        symlinkSync(join(cache, "node_modules/apps"), join(modules, "apps"));

        for (const dep of Object.keys(readManifest(folder.dir).dependencies ?? {})) {
          if (dep === "apps" || !/^(?:@[\w.-]+\/)?[\w-][\w.-]*$/.test(dep)) continue;
          const path = join(folder.dir, "node_modules", dep);

          if (!existsSync(path)) continue;
          mkdirSync(dirname(join(modules, dep)), { recursive: true });
          symlinkSync(path, join(modules, dep));
        }
      } else {
        symlinkSync(join(cache, "node_modules"), join(copy, "node_modules"));
      }

      reporting.progress(`type-checking ${folder.where}`);
      await bun([tsc, "--ignoreConfig", "--noEmit", "--strict", "--skipLibCheck", "--module", "nodenext", "--moduleResolution", "nodenext", "--target", "es2022", "index.ts"], copy, reporting);
    } catch {
      failed.push(folder);
    } finally {
      rmSync(copy, { recursive: true, force: true });
    }
  }

  if (failed.length === 0) return;
  const adopted = failed.some(folder => folder.adopted) ? "; install any extra dependencies in an adopted app's folder before deploying" : "";

  throw new Error(`${failed.map(folder => folder.where).join(", ")} ${failed.length === 1 ? "doesn't" : "don't"} type-check against apps@${version}; nothing was deployed${adopted}`);
}

/** Sets each office app's `apps` dependency to the version Executor serves, editing only that value. */
function matchFramework(folders: readonly AppFolder[], version: string): string[] {
  const lines: string[] = [];

  for (const folder of folders) {
    const path = join(folder.dir, "package.json");
    const before = readManifest(folder.dir).dependencies?.apps;

    if (before === version) continue;

    writeFileSync(path, withFramework(readFileSync(path, "utf8"), version));
    lines.push(`updated ${folder.where}/package.json: apps ${before ?? "(none)"} → ${version}`);
  }

  return lines;
}

type AccountLink = { requirement: string; account: { id: string; label: string; provider?: string } };

/**
 * For each contributed app with an account of its own (scope `app`, other than OpenCode's) that has
 * no linked account of the provider it now declares, a line saying how a person connects it: a link
 * to Executor's own connect page, where they sign in or enter the credential themselves. A link
 * left from before a settings change gave the requirement another provider doesn't count. The
 * request expires after thirty minutes; the next deploy asks again while nothing fits.
 */
async function accountsToConnect(executor: ExecutorAccess, base: string, apps: readonly ExecutorApp[], folders: readonly AppFolder[]): Promise<string[]> {
  const lines: string[] = [];

  for (const app of apps) {
    if (!folders.some((folder) => folder.slug === app.slug && folder.contributor !== undefined)) continue;

    const links = await executor.request<AccountLink[]>("GET", `${base}/apps/${app.id}/accounts/app`);

    for (const [requirement, declared] of Object.entries(app.requirements?.accounts ?? {})) {
      if (requirement === "opencode" || declared.scope !== "app") continue;

      const linked = links.filter((link) => link.requirement === requirement);

      if (linked.some((link) => link.account.provider === declared.provider)) continue;

      const started = await executor.request<{ id: string; url?: string }>("POST", `${base}/apps/${app.id}/accounts/app/${requirement}/connections`, {});
      const again = linked.length === 0 ? "" : " again: its settings changed how it connects";

      lines.push(`${app.slug}: connect its ${requirement} account${again}. Open ${started.url ?? `the ${app.slug} app in Executor's dashboard`} (the link expires in thirty minutes; office apps deploy makes a new one)`);
    }
  }

  return lines;
}

/** What deploy and check start from: the organization path, the served `apps` version, the installed apps and the catalog plan. */
async function served(executor: ExecutorAccess, folders: readonly AppFolder[], catalogApps: readonly string[]) {
  const base = await organizationPath(executor);
  const version = await frameworkVersion(executor, base);
  const existing = await installedApps(executor, base);

  return { base, version, existing, plan: await catalogPlan(executor, base, catalogApps, existing, folders) };
}

/**
 * Deploys `folders` and installs the catalog apps `catalogApps` lists. Returns the summary;
 * `reporting.line` gets what it did, as it does it.
 */
export async function deploy(executor: ExecutorAccess, folders: readonly AppFolder[], catalogApps: readonly string[], reporting: Reporting): Promise<string> {
  reporting.progress("connecting to Executor");
  const { base, version, existing, plan } = await served(executor, folders, catalogApps);
  const authored = folders.filter(folder => !folder.adopted);

  for (const folder of authored) {
    if (existing.find(app => app.slug === folder.slug)?.copiedFrom?.name?.startsWith("@executor.sh/")) {
      throw new Error(`${folder.slug}: local app would overwrite an installed catalog app; adopt it or rename the local folder`);
    }
  }

  // Compare every app first: only a changed one is type-checked, and nothing is written until all pass.
  const compared: { folder: AppFolder; files: UploadFile[]; app: ExecutorApp | undefined; changed: boolean }[] = [];

  for (const folder of folders) {
    const files = sourceFiles(executor.opencode, folder, version);
    const app = existing.find((entry) => entry.slug === folder.slug);

    reporting.progress(`checking ${folder.where}`);
    const same = app?.activeVersion ? await matchesActiveSource(executor, `${base}/apps/${app.id}`, app.activeVersion, files) : false;

    compared.push({ folder, files, app, changed: !same });
  }

  const changed = compared.flatMap(item => item.changed ? [item.folder] : []);

  if (changed.length) await typecheck(executor.opencode, changed, version, reporting);

  for (const line of matchFramework(authored.filter(folder => folder.contributor === undefined), version)) reporting.line(line);

  for (const line of await installMissing(executor, base, plan, existing)) reporting.line(line);
  const active: ExecutorApp[] = [];
  let deployed = 0;

  for (const item of compared) {
    const { folder, files } = item;
    let { app, changed: differs } = item;

    if (app === undefined) {
      // An adopted folder's catalog app may have just been installed; otherwise the app is created.
      app = existing.find(entry => entry.slug === folder.slug);

      if (app === undefined) {
        app = await executor.request<ExecutorApp>("POST", `${base}/apps`, { name: readManifest(folder.dir).executor?.title ?? folder.slug, files });
        reporting.line(`created ${app.slug} (${app.id})`);
      }

      // Installing or creating can already make the upload the active version.
      differs = !(app.activeVersion && await matchesActiveSource(executor, `${base}/apps/${app.id}`, app.activeVersion, files));
    }

    if (!differs) {
      reporting.line(`unchanged ${folder.where} → ${app.slug} (${app.id}) version ${app.activeVersion}`);
    } else {
      reporting.progress(`deploying ${folder.where}`);
      const result = await executor.request<{ app: ExecutorApp }>("POST", `${base}/apps/${app.id}/deploy`, { files });

      app = result.app;
      reporting.line(`deployed ${folder.where} → ${app.slug} (${app.id}) version ${app.activeVersion}`);
      deployed++;
    }

    if (!folder.adopted) active.push(app);
  }

  reporting.progress("checking account links");

  for (const app of active) {
    if (app.requirements?.accounts?.opencode?.scope !== "app") continue;
    const link = await executor.linkOpenCode(app.slug);

    if (link.outcome === "connected") reporting.line(`connected the OpenCode account ${link.account} to ${app.slug}`);
    else if (link.outcome === "linked") reporting.line(`linked the OpenCode account ${link.account} to ${app.slug}`);
  }

  for (const line of await accountsToConnect(executor, base, active, folders)) reporting.line(line);

  return folders.length ? `${deployed} deployed, ${folders.length - deployed} unchanged` : "no local apps to deploy";
}

/**
 * What `office check` reports, with nothing written: a listed catalog app that isn't installed, an
 * office app whose package.json names another `apps` version than Executor serves, and an authored
 * app that isn't deployed or whose deployed source names another version.
 */
export async function frameworkProblems(executor: ExecutorAccess, folders: readonly AppFolder[], catalogApps: readonly string[]): Promise<{ version: string; problems: string[] }> {
  const { base, version, existing, plan } = await served(executor, folders, catalogApps);
  const authored = folders.filter(folder => !folder.adopted);
  const deployed: { slug: string; apps: string | undefined }[] = [];

  for (const app of existing.filter(entry => authored.some(folder => folder.slug === entry.slug))) {
    const source = await executor.request<{ files: { path: string; content?: string }[] }>("GET", `${base}/apps/${app.id}/source`);
    const manifest = source.files.find((file) => file.path === "package.json")?.content;

    deployed.push({ slug: app.slug, apps: manifest === undefined ? undefined : JSON.parse(manifest).dependencies?.apps });
  }

  return {
    version,
    problems: [
      ...plan.filter(item => !item.existing).map(item => `catalog app ${item.id} is missing`),
      // A package's own folder is read-only: deploy sends its manifest with the served version.
      ...authored.filter(folder => folder.contributor === undefined && readManifest(folder.dir).dependencies?.apps !== version).map(folder => `${folder.where} names another apps version`),
      ...deployed.filter(app => app.apps !== version).map(app => `${app.slug} is deployed with apps@${app.apps ?? "?"}`),
      ...authored.filter(folder => !deployed.some(app => app.slug === folder.slug)).map(folder => `${folder.slug} isn't deployed`),
    ],
  };
}
